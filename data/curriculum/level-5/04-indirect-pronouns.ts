import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  understand,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l5-indirect-pronouns',
  title: 'To Me, To You',
  description: 'Le, les and giving, telling, sending',
  emoji: '🎁',
  vocabulary: [
    word('le-di', 'le di', 'I gave him/her', 'grammar', { enAlt: ['i gave him', 'i gave her'] }),
    word('le-dije', 'le dije', 'I told him/her', 'grammar', { enAlt: ['i told him', 'i told her', 'i said to him'] }),
    word('me-dijo', 'me dijo', 'he/she told me', 'grammar', { enAlt: ['he told me', 'she told me', 'she said to me'] }),
    word('les-escribo', 'les escribo', 'I write to them', 'grammar'),
    word('te-mando', 'te mando', "I'll send you", 'grammar', { enAlt: ['i send you'] }),
    word('regalo', 'el regalo', 'present', 'basics', { enAlt: ['gift', 'the present'] }),
    word('se-lo-doy', 'se lo doy', 'I give it to him/her', 'grammar', { enAlt: ['i give it to him', 'i give it to her'] }),
    word('me-lo-das', '¿me lo das?', 'will you give it to me?', 'questions', { enAlt: ['can you give it to me?', 'give it to me?'] }),
  ],
  exercises: [
    tip(
      'Le and les',
      'For "to him / to her / to you (formal)" use *le*; "to them" is *les*. *Le di un regalo* — I gave him/her a present. With *me* and *te* it works the same: *me dijo, te mando*.',
      [
        { spanish: 'Le escribí un mensaje a Pablo.', english: 'I wrote a message to Pablo.' },
        { spanish: '¿Te mando la foto?', english: 'Shall I send you the photo?' },
      ],
    ),
    intro('regalo'),
    intro('le-di'),
    intro('le-dije'),
    intro('me-dijo'),
    speak('Le di un regalo a mi madre', 'I gave my mother a present'),
    meaning('me-dijo'),
    intro('les-escribo'),
    intro('te-mando', { lines: ['*¿Te mando un WhatsApp?* — shall I send you a WhatsApp? Spain runs on WhatsApp.'] }),
    match('le-di', 'le-dije', 'me-dijo', 'les-escribo', 'te-mando'),
    tip(
      'Le + lo = se lo',
      'When *le* or *les* meets *lo, la, los, las*, it changes to *se*: not "le lo" but *se lo*. *¿El regalo? Se lo doy mañana.*',
      [{ spanish: '¿Las fotos? Se las mando esta noche.', english: "The photos? I'll send them to him tonight." }],
    ),
    intro('se-lo-doy'),
    intro('me-lo-das'),
    recall('se-lo-doy'),
    question('*Le* + *lo* becomes…', 'se lo', ['le lo', 'lo le']),
    fill('Mañana ___ escribo un correo a mis profesores.', 'les', ['le', 'los'], "Tomorrow I'll write an email to my teachers."),
    listen('Mi hermano me dijo un secreto', 'My brother told me a secret'),
    order('Le compré un libro a mi padre', 'I bought my father a book'),
    translate("I'll send you the photos", ['Te mando las fotos', 'Te envío las fotos']),
    understand('¿El libro? Se lo di a Ana', ['The book? I gave it to Ana']),
    conversation('Birthday presents', [
      emma(
        'Es el cumpleaños de mi madre. ¿Qué le regalo?',
        "It's my mum's birthday. What should I get her?",
        you(['Regálale {any}', 'Cómprale {any}', 'Le puedes {any}', 'Un {any}', 'Una {any}', 'Unas {any}', 'Unos {any}'], 'Get her some flowers.', {
          hint: 'Regálale unas flores',
          wrong: ['Estaba en casa', 'Me levanto temprano'],
        }),
      ),
      emma(
        '¡Buena idea! ¿Y tú? ¿Qué te regalaron en tu último cumpleaños?',
        'Good idea! And you? What did they give you on your last birthday?',
        you(['Me regalaron {any}', 'Un {any}', 'Una {any}', 'Nada {any}'], 'They gave me a book.', {
          hint: 'Me regalaron un libro',
          wrong: ['Hace frío', 'La conozco'],
        }),
      ),
      emma('¡Qué bien! Luego te mando una foto de las flores.', "Lovely! I'll send you a photo of the flowers later."),
    ]),
  ],
});
