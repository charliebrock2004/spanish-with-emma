import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  understand,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l5-por-para',
  title: 'Por or Para?',
  description: 'The two “for”s — finally explained',
  emoji: '🎯',
  vocabulary: [
    word('para', 'para', 'for / in order to', 'connectors', { enAlt: ['for', 'to', 'in order to'] }),
    word('por', 'por', 'for / through / because of', 'connectors', { enAlt: ['for', 'through', 'by', 'because of'] }),
    word('por-eso', 'por eso', "that's why", 'connectors', { enAlt: ['so', 'for that reason'] }),
    word('gracias-por-todo', 'gracias por todo', 'thanks for everything', 'expressions'),
    word('para-que', 'para qué', 'what for', 'questions', { enAlt: ['what for?', 'why'] }),
    word('por-la-manana', 'por la mañana', 'in the morning', 'time', { enAlt: ['during the morning'] }),
    word('por-ciento', 'por ciento', 'per cent', 'basics', { enAlt: ['percent'] }),
    word('para-manana', 'para mañana', 'by tomorrow', 'time', { enAlt: ['for tomorrow'] }),
  ],
  exercises: [
    tip(
      'Para: destination and purpose',
      'Use *para* for where something is heading: a person (*es para ti*), a place (*salgo para Madrid*), a deadline (*para mañana*) or a goal (*estudio para aprender* — in order to).',
      [
        { spanish: 'Este regalo es para ti.', english: 'This present is for you.' },
        { spanish: 'Estudio español para hablar con mi familia.', english: 'I study Spanish to talk to my family.' },
      ],
    ),
    intro('para'),
    speak('Este café es para ti', 'This coffee is for you'),
    intro('para-manana'),
    intro('para-que'),
    tip(
      'Por: cause, exchange and route',
      'Use *por* for the reason behind something (*gracias por…*, *por el tráfico*), for exchange (*lo compré por diez euros*), for going through (*paseo por el parque*) and parts of the day (*por la mañana*).',
      [
        { spanish: 'Gracias por tu ayuda.', english: 'Thanks for your help.' },
        { spanish: 'Llegué tarde por el tráfico.', english: 'I arrived late because of the traffic.' },
      ],
    ),
    intro('por'),
    intro('gracias-por-todo'),
    intro('por-la-manana'),
    intro('por-eso'),
    intro('por-ciento'),
    match('para', 'por', 'por-eso', 'por-la-manana', 'para-que'),
    meaning('por-eso'),
    recall('para-que'),
    question('*Gracias ___ el regalo.*', 'por', ['para', 'de']),
    question('*El regalo es ___ mi madre.*', 'para', ['por', 'de']),
    fill('Paseamos ___ el centro.', 'por', ['para', 'a'], 'We walked through the centre.'),
    fill('Necesito el informe ___ el viernes.', 'para', ['por', 'en'], 'I need the report by Friday.'),
    fill('Estudio mucho ___ aprobar el examen.', 'para', ['por', 'que'], 'I study a lot in order to pass the exam.'),
    listen('Lo compré por veinte euros', 'I bought it for twenty euros'),
    order('Llueve mucho, por eso no salgo', "It's raining a lot, that's why I'm not going out"),
    translate('Thanks for everything', ['Gracias por todo']),
    understand('¿Para qué sirve esto?', ['What is this for?', "What's this for?"]),
    conversation('Por or para, live', [
      emma(
        '¿Para qué estudias español?',
        'What are you studying Spanish for?',
        you(['Para {any}', 'Porque {any}', 'Estudio español para {any}'], 'To travel around Spain.', {
          hint: 'Para viajar por España',
          wrong: ['Por la mañana', 'Me da igual'],
        }),
      ),
      emma(
        '¡Me encanta! ¿Y cuándo estudias, por la mañana o por la noche?',
        'Love it! And when do you study — in the morning or at night?',
        you(['Por la mañana {any}', 'Por la noche {any}', 'Por la tarde {any}', 'Depende {any}'], 'In the evening.', {
          hint: 'Por la noche',
          wrong: ['Para ti', 'Estoy agobiado'],
        }),
      ),
      emma('Perfecto. Pues gracias por estudiar conmigo. ¡Es un placer!', "Perfect. Well, thanks for studying with me. It's a pleasure!"),
    ]),
  ],
});
