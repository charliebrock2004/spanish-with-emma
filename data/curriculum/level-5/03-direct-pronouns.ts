import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  understand,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l5-direct-pronouns',
  title: 'Lo, La, Los, Las',
  description: 'Say “it” and “them” without repeating yourself',
  emoji: '🔁',
  vocabulary: [
    word('lo-tengo', 'lo tengo', 'I have it', 'grammar', { enAlt: ["i've got it"] }),
    word('la-conozco', 'la conozco', 'I know her', 'grammar', { enAlt: ['i know it'] }),
    word('los-compre', 'los compré', 'I bought them', 'grammar'),
    word('las-veo', 'las veo', 'I see them', 'grammar', { enAlt: ['i can see them'] }),
    word('lo-se', 'lo sé', 'I know', 'expressions', { enAlt: ['i know it'] }),
    word('no-lo-se', 'no lo sé', "I don't know", 'expressions', { enAlt: ['i do not know'] }),
    word('lo-siento-mucho', 'lo siento mucho', "I'm really sorry", 'expressions', { enAlt: ['i am very sorry', "i'm so sorry"] }),
    word('te-quiero', 'te quiero', 'I love you', 'expressions'),
    word('conozco', 'conozco', 'I know (someone / a place)', 'verbs', { enAlt: ['i know'] }),
  ],
  exercises: [
    tip(
      'It and them',
      'To avoid repeating a noun, use *lo* (it/him), *la* (it/her), *los*, *las* (them) — matching the noun. They go *before* the verb: *¿El libro? Lo tengo.*',
      [
        { spanish: '¿Tienes las llaves? — Sí, las tengo.', english: 'Have you got the keys? — Yes, I’ve got them.' },
        { spanish: '¿Conoces a María? — Sí, la conozco.', english: 'Do you know María? — Yes, I know her.' },
      ],
    ),
    intro('lo-tengo'),
    intro('conozco', { lines: ['*Conozco* — I know a person or a place (*saber* is for facts).'] }),
    intro('la-conozco'),
    intro('los-compre'),
    intro('las-veo'),
    speak('¿El pasaporte? Sí, lo tengo', 'The passport? Yes, I have it'),
    meaning('los-compre'),
    question('*¿Tienes la llave?* — Sí, ___ tengo.', 'la', ['lo', 'le']),
    question('*¿Compraste los billetes?* — Sí, ___ compré ayer.', 'los', ['las', 'lo']),
    intro('lo-se', { lines: ['Two everyday classics: *lo sé* — I know. *No lo sé* — I don’t know.'] }),
    intro('no-lo-se'),
    intro('lo-siento-mucho'),
    intro('te-quiero', { lines: ['And the most important one: *te quiero* — I love you. Literally "I want you". Romantic!'] }),
    match('lo-tengo', 'la-conozco', 'lo-se', 'no-lo-se', 'te-quiero'),
    recall('no-lo-se'),
    fill('¿Las gafas? No ___ encuentro.', 'las', ['los', 'la'], "The glasses? I can't find them."),
    listen('¿La película? La vi ayer y me encantó', 'The film? I saw it yesterday and loved it'),
    order('¿Dónde está mi móvil? No lo veo', "Where's my phone? I can't see it"),
    translate("I know her, she's my neighbour", ['La conozco, es mi vecina', 'La conozco. Es mi vecina']),
    understand('¿El vino? Lo compré en el supermercado', ['The wine? I bought it at the supermarket', 'The wine? I bought it in the supermarket']),
    conversation('Packing for a trip', [
      emma(
        '¿Tienes el pasaporte?',
        'Have you got your passport?',
        you(['Sí, lo tengo', 'Sí {any}', 'Lo tengo {any}', 'No {any}', 'No lo tengo {any}'], 'Yes, I’ve got it.', {
          hint: 'Sí, lo tengo',
          wrong: ['Me gustaba jugar', 'Hacía sol'],
        }),
      ),
      emma(
        '¿Y las llaves de casa?',
        'And the house keys?',
        you(['Sí, las tengo', 'Las tengo {any}', 'Sí {any}', 'No {any}', 'No las encuentro {any}', 'No lo sé {any}'], "Yes, I've got them.", {
          hint: 'Sí, las tengo',
          wrong: ['Estaba durmiendo', 'Voy a la playa'],
        }),
      ),
      emma('¡Perfecto! Y el bañador… ¿lo has metido en la maleta?', 'Perfect! And your swimsuit… have you put it in the case?', you(['Sí {any}', 'Lo he metido {any}', 'No {any}', '¡Uy! {any}', 'Todavía no {any}'], "Oops! Not yet!", {
        hint: '¡Uy! Todavía no',
        wrong: ['Me duele el estómago', 'Fui a Toledo'],
      })),
      emma('¡Menos mal que lo he preguntado! 😂', 'Good thing I asked!'),
    ]),
  ],
});
