import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  understand,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l5-future',
  title: 'The Future',
  description: 'Iré, haré, tendré — predictions and promises',
  emoji: '🔮',
  vocabulary: [
    word('ire', 'iré', 'I will go', 'verbs', { enAlt: ["i'll go"] }),
    word('sera', 'será', 'it will be', 'verbs', { enAlt: ["it'll be", 'will be'] }),
    word('hare', 'haré', 'I will do', 'verbs', { enAlt: ["i'll do", 'i will make'] }),
    word('tendre', 'tendré', 'I will have', 'verbs', { enAlt: ["i'll have"] }),
    word('podre', 'podré', 'I will be able to', 'verbs', { enAlt: ["i'll be able to"] }),
    word('habra', 'habrá', 'there will be', 'verbs'),
    word('dentro-de', 'dentro de', 'in (time from now)', 'time', { enAlt: ['in', 'within'] }),
    word('algun-dia', 'algún día', 'one day', 'time', { enAlt: ['someday', 'some day'] }),
    word('seguro-que', 'seguro que', "I'm sure that", 'connectors', { enAlt: ['surely', 'i bet'] }),
    word('quizas', 'quizás', 'maybe', 'connectors', { enAlt: ['perhaps'] }),
  ],
  exercises: [
    tip(
      'The future tense',
      'Take the whole verb and add *-é, -ás, -á, -emos*: *viajaré, comerás, vivirá*. A few change their stem: *haré* (hacer), *tendré* (tener), *podré* (poder), *habrá* (hay).',
      [
        { spanish: 'Mañana lloverá.', english: 'It will rain tomorrow.' },
        { spanish: 'Algún día viviré en España.', english: 'One day I will live in Spain.' },
      ],
    ),
    intro('ire'),
    intro('sera'),
    intro('hare'),
    intro('tendre'),
    meaning('tendre'),
    intro('podre'),
    intro('habra'),
    match('ire', 'sera', 'hare', 'tendre', 'podre'),
    intro('algun-dia'),
    speak('Algún día hablaré español perfectamente', 'One day I will speak Spanish perfectly'),
    intro('dentro-de', { lines: ['*Dentro de un año* — in a year’s time.'] }),
    intro('seguro-que'),
    intro('quizas'),
    recall('quizas'),
    question('"I will travel" is…', 'viajaré', ['viajé', 'viajaba']),
    fill('Dentro de dos años ___ en Madrid.', 'viviré', ['vivía', 'viví'], 'In two years I will live in Madrid.'),
    fill('¿Qué ___ este verano?', 'harás', ['hiciste', 'hacías'], 'What will you do this summer?'),
    listen('Seguro que mañana hará buen tiempo', "I'm sure the weather will be nice tomorrow"),
    order('Quizás iré a México el año que viene', "Maybe I'll go to Mexico next year"),
    translate('It will be amazing', ['Será increíble', '¡Será increíble!']),
    understand('Habrá mucha gente en la fiesta', ['There will be lots of people at the party', 'There will be a lot of people at the party']),
    conversation('Your future', [
      emma(
        '¿Dónde te ves dentro de cinco años?',
        'Where do you see yourself in five years?',
        you(['Viviré {any}', 'Estaré {any}', 'Seré {any}', 'Tendré {any}', 'Quizás {any}', 'Trabajaré {any}', 'Dentro de {any}'], "I'll live in Spain.", {
          hint: 'Viviré en España',
          wrong: ['Vivía en un pueblo', 'Le di un regalo'],
        }),
      ),
      emma(
        '¡Me encanta! ¿Y hablarás español con fluidez?',
        'Love it! And will you speak Spanish fluently?',
        you(['¡Claro! {any}', 'Claro {any}', 'Sí {any}', 'Seguro que sí {any}', 'Eso espero {any}', 'Quizás {any}', 'Hablaré {any}'], 'Of course!', {
          hint: '¡Claro que sí!',
          wrong: ['Me duele la garganta', 'Estaba durmiendo'],
        }),
      ),
      emma('Seguro que sí. Y yo estaré ahí para verlo.', "I'm sure you will. And I'll be there to see it."),
    ]),
  ],
});
