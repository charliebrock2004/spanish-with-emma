import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  understand,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l6-emotions',
  title: 'I’m So Glad That…',
  description: 'Reactions with the subjunctive',
  emoji: '🥹',
  vocabulary: [
    word('me-alegro-de-que', 'me alegro de que', "I'm glad that", 'feelings', { enAlt: ["i'm happy that"] }),
    word('me-molesta-que', 'me molesta que', 'it bothers me that', 'feelings', { enAlt: ['it annoys me that'] }),
    word('es-una-pena-que', 'es una pena que', "it's a shame that", 'feelings', { enAlt: ["it's a pity that"] }),
    word('me-encanta-que', 'me encanta que', 'I love it that', 'feelings', { enAlt: ['i love that'] }),
    word('me-sorprende-que', 'me sorprende que', "I'm surprised that", 'feelings', { enAlt: ['it surprises me that'] }),
    word('tengo-miedo-de-que', 'tengo miedo de que', "I'm afraid that", 'feelings', { enAlt: ["i'm scared that"] }),
    word('me-da-rabia-que', 'me da rabia que', 'it drives me mad that', 'feelings', { enAlt: ['it makes me angry that', 'it annoys me that'] }),
  ],
  exercises: [
    tip(
      'Feelings + que + subjunctive',
      'When you react emotionally to what *someone else* does, the second verb goes into the subjunctive: *me alegro de que estés aquí*. Same person? Use the infinitive: *me alegro de estar aquí*.',
      [
        { spanish: 'Me alegro de que te guste.', english: "I'm glad you like it." },
        { spanish: 'Me molesta que llegues tarde.', english: 'It bothers me that you arrive late.' },
      ],
    ),
    intro('me-alegro-de-que'),
    speak('Me alegro de que estés aquí', "I'm glad you're here"),
    intro('me-encanta-que'),
    intro('es-una-pena-que'),
    intro('me-molesta-que'),
    meaning('me-molesta-que'),
    intro('me-sorprende-que'),
    intro('tengo-miedo-de-que'),
    intro('me-da-rabia-que', { lines: ['Very Spanish: *¡me da rabia!* — it drives me mad!'] }),
    match('me-alegro-de-que', 'me-molesta-que', 'es-una-pena-que', 'me-sorprende-que', 'tengo-miedo-de-que'),
    recall('es-una-pena-que'),
    question('*Me alegro de que ___ (tú) bien.*', 'estés', ['estás', 'estar']),
    fill('Es una pena que no ___ venir.', 'puedas', ['puedes', 'poder'], "It's a shame you can't come."),
    fill('Me encanta que ___ español conmigo.', 'hables', ['hablas', 'hablar'], 'I love that you speak Spanish with me.'),
    question('Same person, so no subjunctive: *Me alegro de ___ aquí.*', 'estar', ['esté', 'estés']),
    listen('Me sorprende que no haya nadie', "I'm surprised there's nobody here"),
    order('Tengo miedo de que llueva mañana', "I'm afraid it'll rain tomorrow"),
    translate("I'm glad you like it", ['Me alegro de que te guste']),
    understand('Me da rabia que la gente hable en el cine', ['It drives me mad that people talk in the cinema', 'It annoys me when people talk in the cinema']),
    conversation('Pet peeves and little joys', [
      emma(
        'Una cosa que me molesta: que la gente no diga "gracias". ¿Y a ti?',
        'Something that bothers me: when people don’t say "thanks". And you?',
        you(['Me molesta que {any}', 'Me da rabia que {any}', 'A mí {any}', 'No me gusta que {any}'], 'It bothers me when people are late.', {
          hint: 'Me molesta que la gente llegue tarde',
          wrong: ['Fui a la playa', 'Lo compré ayer'],
        }),
      ),
      emma(
        '¡Totalmente! ¿Y algo que te encanta?',
        'Totally! And something you love?',
        you(['Me encanta que {any}', 'Me encanta {any}', 'Me alegra que {any}', 'Me gusta que {any}'], 'I love it when the sun shines.', {
          hint: 'Me encanta que haga sol',
          wrong: ['Tengo fiebre', 'Estaba durmiendo'],
        }),
      ),
      emma('A mí me encanta que practiques conmigo. De verdad.', 'I love that you practise with me. Really.'),
    ]),
  ],
});
