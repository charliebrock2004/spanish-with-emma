import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  understand,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l6-hypotheticals',
  title: 'If I Won the Lottery…',
  description: 'Si tuviera, si pudiera — dreaming out loud',
  emoji: '💫',
  vocabulary: [
    word('si-tuviera', 'si tuviera', 'if I had', 'grammar'),
    word('si-pudiera', 'si pudiera', 'if I could', 'grammar', { enAlt: ['if i were able to'] }),
    word('si-fuera', 'si fuera', 'if I were', 'grammar', { enAlt: ['if i was'] }),
    word('si-supiera', 'si supiera', 'if I knew', 'grammar'),
    word('si-me-tocara-la-loteria', 'si me tocara la lotería', 'if I won the lottery', 'expressions', { enAlt: ['if i won the lotto'] }),
    word('ojala-pudiera', 'ojalá pudiera', 'I wish I could', 'expressions'),
    word('como-si', 'como si', 'as if', 'connectors', { enAlt: ['as though'] }),
  ],
  exercises: [
    tip(
      'Si + past subjunctive + conditional',
      'For imaginary situations: *si* + past subjunctive, then the conditional. Take the *ellos* past form (*tuvieron*), drop *-ron*, add *-ra*: *tuviera, pudiera, fuera*.',
      [
        { spanish: 'Si tuviera tiempo, aprendería a bailar flamenco.', english: 'If I had time, I’d learn to dance flamenco.' },
        { spanish: 'Si fuera tú, iría.', english: 'If I were you, I’d go.' },
      ],
    ),
    intro('si-tuviera'),
    intro('si-pudiera'),
    speak('Si pudiera, viviría en la playa', 'If I could, I would live on the beach'),
    intro('si-fuera'),
    intro('si-supiera'),
    meaning('si-supiera'),
    intro('si-me-tocara-la-loteria', { lines: ['The classic dream: *si me tocara la lotería…* — literally "if the lottery touched me".'] }),
    intro('ojala-pudiera'),
    intro('como-si', { lines: ['*Como si* always takes the past subjunctive: *habla como si fuera experto*.'] }),
    match('si-tuviera', 'si-pudiera', 'si-fuera', 'si-supiera', 'como-si'),
    recall('si-pudiera'),
    question('*Si ___ dinero, viajaría por el mundo.*', 'tuviera', ['tengo', 'tendría']),
    fill('Si fuera rico, ___ una casa en Mallorca.', 'compraría', ['compraré', 'compro'], "If I were rich, I'd buy a house in Mallorca."),
    fill('Ojalá ___ quedarme más tiempo.', 'pudiera', ['puedo', 'podré'], 'I wish I could stay longer.'),
    listen('Si supiera la respuesta, te la diría', "If I knew the answer, I'd tell you"),
    order('Si me tocara la lotería, dejaría mi trabajo', "If I won the lottery, I'd quit my job"),
    translate('If I had more time, I would read more', ['Si tuviera más tiempo, leería más']),
    understand('Habla como si lo supiera todo', ['He talks as if he knew everything', 'She talks as if she knew everything', 'He speaks as if he knew everything']),
    conversation('Dream big', [
      emma(
        'Si te tocara la lotería mañana, ¿qué harías primero?',
        'If you won the lottery tomorrow, what would you do first?',
        you(['Compraría {any}', 'Viajaría {any}', 'Dejaría {any}', 'Iría {any}', 'Haría {any}', 'Primero {any}', 'Le daría {any}', 'Invitaría {any}'], "I'd travel around the world.", {
          hint: 'Viajaría por todo el mundo',
          wrong: ['Me alegro de que', 'Tengo frío'],
        }),
      ),
      emma(
        '¡Me apunto! Y si pudieras hablar con cualquier persona, ¿con quién hablarías?',
        "Count me in! And if you could talk to anyone, who would you talk to?",
        you(['Hablaría con {any}', 'Con {any}', 'Me gustaría hablar con {any}'], "I'd talk to my grandmother.", {
          hint: 'Hablaría con mi abuela',
          wrong: ['Dudo que venga', 'Fui a Roma'],
        }),
      ),
      emma('Qué bonito. Yo hablaría con Cervantes… y le preguntaría por qué el Quijote es tan largo. 😅', "That’s lovely. I'd talk to Cervantes… and ask him why Don Quixote is so long."),
    ]),
  ],
});
