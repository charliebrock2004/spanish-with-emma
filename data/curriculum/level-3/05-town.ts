import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l3-town',
  title: 'Around Town',
  description: 'Places in the city — and hay vs está',
  emoji: '🏙️',
  vocabulary: [
    word('ciudad', 'la ciudad', 'city', 'places', { pron: 'la thyoo-DAD', enAlt: ['town', 'the city'] }),
    word('banco', 'el banco', 'bank', 'places', { pron: 'el BAN-ko', enAlt: ['the bank'], note: '*Banco* also means "bench"!' }),
    word('farmacia', 'la farmacia', 'pharmacy', 'places', { pron: 'la far-MA-thya', enAlt: ["chemist's", 'chemist', 'the pharmacy'] }),
    word('supermercado', 'el supermercado', 'supermarket', 'places', { pron: 'el soo-per-mer-KA-do', enAlt: ['the supermarket'] }),
    word('estacion', 'la estación', 'station', 'places', { pron: 'la es-ta-THYON', enAlt: ['the station', 'train station'] }),
    word('museo', 'el museo', 'museum', 'places', { pron: 'el moo-SEH-o', enAlt: ['the museum'] }),
    word('playa', 'la playa', 'beach', 'places', { pron: 'la PLA-ya', enAlt: ['the beach'] }),
    word('plaza', 'la plaza', 'square', 'places', { pron: 'la PLA-tha', enAlt: ['the square', 'town square'] }),
    word('esta', 'está', 'is (located)', 'verbs', { pron: 'es-TA', enAlt: ['is'] }),
    word('cerca', 'cerca', 'near', 'places', { pron: 'THER-ka', enAlt: ['close', 'nearby'] }),
    word('lejos', 'lejos', 'far', 'places', { pron: 'LEH-hos', enAlt: ['far away'] }),
  ],
  exercises: [
    intro('ciudad', { lines: ['Let’s explore *la ciudad* — the city.'] }),
    intro('plaza', { lines: ['Every Spanish town has *una plaza* — a square where everyone meets.'] }),
    intro('banco'),
    intro('farmacia', { lines: ['*La farmacia* — look for the green cross.'] }),
    intro('supermercado'),
    meaning('farmacia'),
    intro('estacion'),
    intro('museo'),
    intro('playa'),
    match('banco', 'farmacia', 'supermercado', 'estacion', 'museo', 'playa'),
    tip(
      'Hay or está?',
      'Use *hay* when something exists or you mention it for the first time: *hay un banco en la plaza*. Use *está* for where a specific thing is: *el banco está en la plaza*.',
      [
        { spanish: '¿Hay una farmacia por aquí?', english: 'Is there a pharmacy around here?' },
        { spanish: '¿Dónde está la estación?', english: 'Where is the station?' },
      ],
    ),
    intro('esta'),
    question('Which fits? *¿Dónde ___ el museo?*', 'está', ['hay', 'es']),
    fill('___ un supermercado cerca.', 'Hay', ['Está', 'Es'], "There's a supermarket nearby.", { explanation: 'Mentioning that something exists → *hay*.' }),
    intro('cerca'),
    intro('lejos'),
    recall('lejos'),
    speak('¿Hay una farmacia por aquí?', 'Is there a pharmacy around here?'),
    listen('La playa está muy cerca', 'The beach is very near'),
    order('El museo está lejos de la estación', 'The museum is far from the station'),
    translate('Where is the bank?', ['¿Dónde está el banco?']),
    conversation('Emma’s town', [
      emma('Mi barrio es genial. Hay una plaza muy bonita.', 'My neighbourhood is great. There’s a really pretty square.'),
      emma(
        '¿Y en tu barrio? ¿Qué hay?',
        'And in your neighbourhood? What is there?',
        you(['Hay {any}', 'En mi barrio hay {any}', 'Tiene {any}'], "There's a supermarket and a park.", {
          hint: 'Hay un supermercado y un parque',
          wrong: ['Me llamo Emma', 'Hace calor'],
        }),
      ),
      emma(
        '¿La playa está cerca o lejos de tu casa?',
        'Is the beach near or far from your house?',
        you(['Está cerca {any}', 'Está lejos {any}', 'Cerca {any}', 'Lejos {any}', 'Muy lejos {any}', 'No hay playa {any}'], "It's far.", {
          hint: 'Está lejos',
          wrong: ['Tengo dos hermanos', 'Son las siete'],
        }),
      ),
      emma('¡Qué pena! Tienes que venir a Valencia.', 'What a shame! You’ll have to come to Valencia.'),
    ]),
  ],
});
