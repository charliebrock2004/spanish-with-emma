import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  understand,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l3-directions',
  title: 'Finding Your Way',
  description: 'Ask for directions and understand the answer',
  emoji: '🧭',
  vocabulary: [
    word('perdone', 'perdone', 'excuse me', 'expressions', { pron: 'per-DO-neh', note: 'Polite, for strangers (*usted*). With friends: *perdona*.' }),
    word('donde-esta', '¿dónde está…?', 'where is…?', 'questions', { pron: 'DON-deh es-TA' }),
    word('a-la-derecha', 'a la derecha', 'on the right', 'places', { pron: 'a la deh-REH-cha', enAlt: ['to the right', 'right'] }),
    word('a-la-izquierda', 'a la izquierda', 'on the left', 'places', { pron: 'a la eeth-KYER-da', enAlt: ['to the left', 'left'] }),
    word('todo-recto', 'todo recto', 'straight on', 'places', { pron: 'TO-do REK-to', enAlt: ['straight ahead'] }),
    word('gire', 'gire', 'turn', 'verbs', { pron: 'HEE-reh', note: 'Formal. With friends: *gira*.' }),
    word('calle', 'la calle', 'street', 'places', { pron: 'la KA-yeh', enAlt: ['the street', 'road'] }),
    word('esquina', 'la esquina', 'corner', 'places', { pron: 'la es-KEE-na', enAlt: ['the corner'] }),
    word('al-lado-de', 'al lado de', 'next to', 'places', { pron: 'al LA-do deh', enAlt: ['beside'] }),
    word('enfrente-de', 'enfrente de', 'opposite', 'places', { pron: 'en-FREN-teh deh', enAlt: ['across from', 'in front of'] }),
  ],
  exercises: [
    intro('perdone', { lines: ['Stopping a stranger? Start with *perdone* — excuse me.'] }),
    intro('donde-esta'),
    speak('Perdone, ¿dónde está la estación?', 'Excuse me, where is the station?'),
    intro('todo-recto'),
    intro('a-la-derecha'),
    intro('a-la-izquierda', { lines: ['*Izquierda* — left. It’s a mouthful: eeth-KYER-da.'] }),
    meaning('a-la-izquierda'),
    intro('gire', { lines: ['*Gire a la derecha* — turn right.'] }),
    intro('calle'),
    intro('esquina'),
    match('todo-recto', 'a-la-derecha', 'a-la-izquierda', 'calle', 'esquina'),
    tip(
      'Understanding directions',
      'People speak fast, so listen for the key words: *derecha*, *izquierda*, *todo recto*, and the street — *la primera* (the first), *la segunda* (the second).',
      [
        { spanish: 'Siga todo recto y gire a la izquierda.', english: 'Go straight on and turn left.' },
        { spanish: 'Es la segunda calle a la derecha.', english: "It's the second street on the right." },
      ],
    ),
    listen('Gire a la derecha en la esquina', 'Turn right at the corner'),
    intro('al-lado-de'),
    intro('enfrente-de'),
    recall('enfrente-de'),
    fill('La farmacia está al lado ___ banco.', 'del', ['de la', 'en el'], 'The pharmacy is next to the bank.', {
      explanation: '*De + el* joins up to make *del*.',
    }),
    question('Someone says *todo recto*. You…', 'keep going straight', ['turn right', 'turn back']),
    order('Siga todo recto y gire a la izquierda', 'Go straight on and turn left'),
    translate("It's opposite the museum", ['Está enfrente del museo']),
    understand('Es la primera calle a la derecha', ["It's the first street on the right", 'It is the first street on the right']),
    conversation('Lost in Madrid', [
      emma(
        '¡Hola! ¿Te puedo ayudar? Pareces perdido.',
        'Hi! Can I help? You look lost.',
        you(['¿Dónde está {any}', 'Perdone {any}', 'Sí {any}', 'Busco {any}'], 'Where is the Prado Museum?', {
          hint: '¿Dónde está el Museo del Prado?',
          wrong: ['Me gusta la tortilla', 'Tengo veinte años'],
        }),
      ),
      emma('¡Fácil! Sigue todo recto y gira a la derecha. Está enfrente de un hotel.', 'Easy! Go straight on and turn right. It’s opposite a hotel.'),
      emma(
        '¿Lo tienes?',
        'Got it?',
        you(['Todo recto y a la derecha {any}', 'Sí {any}', 'Vale {any}', '¿A la derecha?'], 'Straight on and right. Thanks!', {
          hint: 'Todo recto y a la derecha. ¡Gracias!',
          wrong: ['Llevo una chaqueta', 'Son las diez'],
        }),
      ),
      emma('¡Eso es! Disfruta del museo.', "That's it! Enjoy the museum."),
    ]),
  ],
});
