import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  recall,
  speak,
  tip,
  translate,
  understand,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l2-drinks',
  title: 'Something to Drink?',
  description: 'Water, coffee, juice — and asking for what you want',
  emoji: '☕',
  vocabulary: [
    word('agua', 'el agua', 'water', 'drinks', { pron: 'el A-gwa', enAlt: ['the water'], note: '*Agua* is feminine but takes *el* — it just sounds better.' }),
    word('cafe', 'el café', 'coffee', 'drinks', { pron: 'el ka-FEH', enAlt: ['the coffee', 'a coffee'] }),
    word('te', 'el té', 'tea', 'drinks', { pron: 'el TEH', enAlt: ['the tea'] }),
    word('leche', 'la leche', 'milk', 'drinks', { pron: 'la LEH-cheh', enAlt: ['the milk'] }),
    word('zumo', 'el zumo', 'juice', 'drinks', { pron: 'el THOO-mo', enAlt: ['the juice'], note: 'In Spain it’s *zumo*; in Latin America, *jugo*.' }),
    word('cerveza', 'la cerveza', 'beer', 'drinks', { pron: 'la ther-BEH-tha', enAlt: ['the beer', 'a beer'] }),
    word('vino', 'el vino', 'wine', 'drinks', { pron: 'el BEE-no', enAlt: ['the wine'] }),
    word('quiero', 'quiero', 'I want', 'verbs', { pron: 'KYEH-ro', enAlt: ["i'd like", 'i would like'] }),
    word('quieres', '¿quieres…?', 'do you want…?', 'verbs', { pron: 'KYEH-res', enAlt: ['do you want', 'would you like'] }),
    word('con', 'con', 'with', 'connectors', { pron: 'kon' }),
    word('sin', 'sin', 'without', 'connectors', { pron: 'seen' }),
  ],
  exercises: [
    intro('agua', { lines: ['First things first: *el agua* — water.'] }),
    intro('cafe'),
    intro('te'),
    intro('leche'),
    meaning('leche'),
    intro('quiero', { lines: ['*Quiero* — I want. *Quiero un café.* Add *por favor* and you’re perfectly polite.'] }),
    speak('Quiero un café, por favor', "I'd like a coffee, please"),
    intro('con'),
    intro('sin', { lines: ['*Con leche* — with milk. *Sin azúcar* — without sugar.'] }),
    translate('A coffee with milk, please', ['Un café con leche, por favor', 'Café con leche, por favor', 'Un café con leche']),
    intro('zumo'),
    intro('cerveza'),
    intro('vino'),
    match('agua', 'cafe', 'te', 'zumo', 'vino'),
    recall('cerveza'),
    intro('quieres', { lines: ['Offering? *¿Quieres un té?* — Do you want a tea?'] }),
    tip(
      'Un or una?',
      'Masculine words take *un* (a) and *el* (the); feminine words take *una* and *la*. *Un café, una cerveza.*',
      [
        { spanish: 'Un zumo de naranja.', english: 'An orange juice.' },
        { spanish: 'Una cerveza, por favor.', english: 'A beer, please.' },
      ],
    ),
    fill('___ cerveza, por favor.', 'Una', ['Un', 'Unos'], 'A beer, please.', { explanation: '*Cerveza* is feminine → *una*.' }),
    listen('¿Quieres un vaso de agua?', 'Do you want a glass of water?'),
    order('Quiero un zumo de naranja', 'I want an orange juice'),
    understand('Un té sin leche, por favor', ['A tea without milk, please', 'Tea without milk, please', 'A tea with no milk, please']),
    conversation('At Emma’s kitchen table', [
      emma(
        '¡Hola! ¿Quieres un café?',
        'Hi! Do you want a coffee?',
        you(['Sí {any}', 'No {any}', 'Quiero {any}', 'Un café {any}', 'Un té {any}'], 'Yes, please.', {
          hint: 'Sí, por favor',
          wrong: ['Mi madre se llama Ana', 'Me llamo Emma'],
        }),
      ),
      emma(
        '¿Con leche o sin leche?',
        'With or without milk?',
        you(['Con leche {any}', 'Sin leche {any}', 'Con {any}', 'Sin {any}'], 'With milk, please.', {
          hint: 'Con leche, por favor',
          wrong: ['Tengo dos hermanas', 'Adiós'],
        }),
      ),
      emma('¡Marchando! Un café para ti.', "Coming right up! A coffee for you."),
    ]),
  ],
});
