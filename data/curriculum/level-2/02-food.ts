import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l2-food',
  title: 'Food I Love',
  description: 'Say what you like — and what you really don’t',
  emoji: '🥘',
  vocabulary: [
    word('comida', 'la comida', 'food', 'food', { pron: 'la ko-MEE-da', enAlt: ['the food', 'lunch'] }),
    word('me-gusta', 'me gusta', 'I like', 'food', { pron: 'meh GOOS-ta' }),
    word('no-me-gusta', 'no me gusta', "I don't like", 'food', { pron: 'no meh GOOS-ta', enAlt: ['i do not like'] }),
    word('me-encanta', 'me encanta', 'I love', 'food', { pron: 'meh en-KAN-ta' }),
    word('pan', 'el pan', 'bread', 'food', { pron: 'el PAN', enAlt: ['the bread'] }),
    word('queso', 'el queso', 'cheese', 'food', { pron: 'el KEH-so', enAlt: ['the cheese'] }),
    word('fruta', 'la fruta', 'fruit', 'food', { pron: 'la FROO-ta', enAlt: ['the fruit'] }),
    word('manzana', 'la manzana', 'apple', 'food', { pron: 'la man-THA-na', enAlt: ['the apple'], note: 'In Spain, *z* sounds like the "th" in "think".' }),
    word('pollo', 'el pollo', 'chicken', 'food', { pron: 'el PO-yo', enAlt: ['the chicken'] }),
    word('pescado', 'el pescado', 'fish', 'food', { pron: 'el pes-KA-do', enAlt: ['the fish'] }),
    word('tortilla', 'la tortilla', 'Spanish omelette', 'food', {
      pron: 'la tor-TEE-ya',
      enAlt: ['omelette', 'spanish omelet', 'potato omelette', 'tortilla'],
    }),
  ],
  exercises: [
    intro('comida', { lines: ['*La comida* — food. My favourite topic, honestly.'] }),
    intro('pan'),
    intro('queso'),
    meaning('queso'),
    intro('me-gusta', { lines: ['*Me gusta* — I like. *Me gusta el queso.*'] }),
    speak('Me gusta el queso', 'I like cheese'),
    intro('no-me-gusta', { lines: ['Just put *no* in front: *no me gusta*.'] }),
    intro('fruta'),
    intro('manzana'),
    tip(
      'Gusta or gustan?',
      '*Me gusta* literally means "it pleases me", so it follows the thing you like. One thing: *me gusta*. More than one: *me gustan*.',
      [
        { spanish: 'Me gusta la fruta.', english: 'I like fruit.' },
        { spanish: 'Me gustan las manzanas.', english: 'I like apples.' },
      ],
    ),
    fill('Me ___ las manzanas.', 'gustan', ['gusta', 'gusto'], 'I like apples.', {
      explanation: '*Las manzanas* is plural, so it’s *me gustan*.',
    }),
    intro('pollo'),
    intro('pescado'),
    match('pan', 'queso', 'pollo', 'pescado', 'manzana'),
    intro('tortilla', { lines: ['In Spain, *la tortilla* is a thick potato omelette — not a wrap! Order it anywhere.'] }),
    intro('me-encanta', { lines: ['Love it? *Me encanta.*'] }),
    recall('pescado'),
    order('No me gusta el pescado', "I don't like fish"),
    translate('I love Spanish omelette', ['Me encanta la tortilla', 'Me encanta la tortilla española']),
    listen('¿Te gusta el pollo?', 'Do you like chicken?'),
    question('Someone asks *¿Te gusta el queso?* You love it. What do you say?', 'Sí, me encanta', ['No, gracias', 'Me llamo Emma']),
    conversation('Food you love', [
      emma(
        '¿Te gusta la comida española?',
        'Do you like Spanish food?',
        you(['Sí {any}', 'Me gusta {any}', 'Me encanta {any}', 'No {any}'], 'Yes, I love it.', {
          hint: 'Sí, me encanta',
          wrong: ['Tengo un hermano', 'Buenas noches'],
        }),
      ),
      emma(
        '¿Te gusta la tortilla?',
        'Do you like Spanish omelette?',
        you(['Sí {any}', 'Me gusta {any}', 'Me encanta {any}', 'No me gusta {any}', 'No {any}'], 'Yes, I like it.', {
          hint: 'Sí, me gusta',
          wrong: ['Mi padre se llama Juan', 'Hasta luego'],
        }),
      ),
      emma('¡A mí también! Con un poco de pan… perfecto.', 'Me too! With a bit of bread… perfect.'),
    ]),
  ],
});
