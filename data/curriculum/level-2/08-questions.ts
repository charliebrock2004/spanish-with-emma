import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  understand,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l2-questions',
  title: 'Asking Questions',
  description: 'What, where, when, how, who and why',
  emoji: '❓',
  vocabulary: [
    word('que', '¿qué?', 'what?', 'questions', { pron: 'KEH' }),
    word('donde', '¿dónde?', 'where?', 'questions', { pron: 'DON-deh' }),
    word('cuando', '¿cuándo?', 'when?', 'questions', { pron: 'KWAN-do' }),
    word('como', '¿cómo?', 'how?', 'questions', { pron: 'KO-mo' }),
    word('quien', '¿quién?', 'who?', 'questions', { pron: 'KYEN' }),
    word('por-que', '¿por qué?', 'why?', 'questions', { pron: 'por KEH' }),
    word('porque', 'porque', 'because', 'connectors', { pron: 'POR-keh' }),
    word('cuanto', '¿cuánto?', 'how much?', 'questions', { pron: 'KWAN-to', note: 'For things you count: *¿cuántos?* — how many?' }),
    word('donde-vives', '¿dónde vives?', 'where do you live?', 'questions', { pron: 'DON-deh BEE-bes' }),
  ],
  exercises: [
    tip(
      'Two question marks',
      'Spanish questions open with *¿* and close with *?* — so you know it’s a question from the start. Question words always carry an accent: *¿qué?, ¿dónde?, ¿cómo?*',
      [{ spanish: '¿Dónde está el baño?', english: 'Where is the bathroom?' }],
    ),
    intro('que', { lines: ['*¿Qué?* — what? *¿Qué es esto?* — what’s this?'] }),
    intro('donde'),
    intro('cuando'),
    meaning('donde'),
    intro('como', { lines: ['You know this one! *¿Cómo estás?* — how are you?'] }),
    intro('quien'),
    match('que', 'donde', 'cuando', 'como', 'quien'),
    intro('por-que', { lines: ['*¿Por qué?* — why? Written as two words, with an accent.'] }),
    intro('porque', { lines: ['And the answer: *porque* — because. One word, no accent. Sneaky!'] }),
    question('Which one means "because"?', 'porque', ['¿por qué?', '¿qué?']),
    intro('cuanto'),
    recall('cuando'),
    intro('donde-vives'),
    speak('¿Dónde vives?', 'Where do you live?'),
    fill('¿___ se llama tu madre?', 'Cómo', ['Dónde', 'Cuándo'], "What's your mother's name?", {
      explanation: 'Spanish asks "how is she called?" — *¿cómo se llama?*',
    }),
    listen('¿Cuándo es tu cumpleaños?', 'When is your birthday?'),
    order('¿Por qué estudias español?', 'Why are you studying Spanish?'),
    translate('Who is Emma?', ['¿Quién es Emma?', 'Quién es Emma']),
    understand('¿Cuánto cuesta el café?', ['How much is the coffee?', 'How much does the coffee cost?']),
    conversation('Twenty questions (well, three)', [
      emma(
        '¿Dónde vives?',
        'Where do you live?',
        you(['Vivo en {any}', 'En {any}'], 'I live in Glasgow.', { hint: 'Vivo en Glasgow', wrong: ['Me gusta nadar', 'Son las cinco'] }),
      ),
      emma(
        '¡Qué bien! ¿Por qué estudias español?',
        'Great! Why are you learning Spanish?',
        you(['Porque {any}', 'Para {any}', 'Me gusta {any}', 'Me encanta {any}'], 'Because I love Spain.', {
          hint: 'Porque me encanta España',
          wrong: ['Tengo un hermano', 'Buenos días'],
        }),
      ),
      emma('¡Me encanta tu respuesta!', 'I love your answer!'),
    ]),
  ],
});
