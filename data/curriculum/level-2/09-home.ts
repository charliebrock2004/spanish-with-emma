import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l2-home',
  title: 'Home Sweet Home',
  description: 'Rooms, your flat and “there is”',
  emoji: '🏠',
  vocabulary: [
    word('casa', 'la casa', 'house', 'home', { pron: 'la KA-sa', enAlt: ['home', 'the house'] }),
    word('piso', 'el piso', 'flat', 'home', { pron: 'el PEE-so', enAlt: ['apartment', 'the flat'], note: 'In Spain a flat is *un piso*. It also means "floor".' }),
    word('cocina', 'la cocina', 'kitchen', 'home', { pron: 'la ko-THEE-na', enAlt: ['the kitchen'] }),
    word('dormitorio', 'el dormitorio', 'bedroom', 'home', { pron: 'el dor-mee-TO-ryo', enAlt: ['the bedroom'] }),
    word('bano', 'el baño', 'bathroom', 'home', { pron: 'el BA-nyo', enAlt: ['the bathroom', 'toilet', 'loo'] }),
    word('salon', 'el salón', 'living room', 'home', { pron: 'el sa-LON', enAlt: ['lounge', 'sitting room', 'the living room'] }),
    word('jardin', 'el jardín', 'garden', 'home', { pron: 'el har-DEEN', enAlt: ['the garden'] }),
    word('grande', 'grande', 'big', 'adjectives', { pron: 'GRAN-deh', enAlt: ['large'] }),
    word('pequeno', 'pequeño', 'small', 'adjectives', { pron: 'peh-KEH-nyo', alt: ['pequeña'], enAlt: ['little'] }),
    word('hay', 'hay', 'there is', 'basics', { pron: 'AI (like "eye")', enAlt: ['there are'] }),
  ],
  exercises: [
    intro('casa'),
    intro('piso', { lines: ['Most people in Spanish cities live in *un piso* — a flat.'] }),
    meaning('piso'),
    intro('cocina'),
    intro('dormitorio'),
    intro('bano'),
    intro('salon'),
    match('cocina', 'dormitorio', 'bano', 'salon', 'casa'),
    intro('hay', { lines: ['*Hay* — there is, there are. One tiny word, sounds like "eye".'] }),
    tip(
      'Hay',
      '*Hay* works for one thing or many: *hay un baño*, *hay dos dormitorios*. To ask: *¿hay…?* — is there…?',
      [
        { spanish: 'Hay una cocina grande.', english: "There's a big kitchen." },
        { spanish: '¿Hay jardín?', english: 'Is there a garden?' },
      ],
    ),
    speak('Hay dos dormitorios', 'There are two bedrooms'),
    intro('jardin'),
    intro('grande'),
    intro('pequeno', { lines: ['*Pequeño* — small. The *ñ* sounds like the "ny" in "canyon".'] }),
    recall('pequeno'),
    tip(
      'Adjectives come after',
      'In Spanish the describing word usually goes after the thing: *una casa grande* — a big house. And it matches: *un piso pequeño, una cocina pequeña*.',
      [{ spanish: 'Vivo en un piso pequeño.', english: 'I live in a small flat.' }],
    ),
    question('"A small kitchen" is…', 'una cocina pequeña', ['una cocina pequeño', 'un cocina pequeña'], {
      explanation: '*Cocina* is feminine, so everything matches: *una cocina pequeña*.',
    }),
    fill('Vivo en un piso ___.', 'pequeño', ['pequeña', 'pequeños'], 'I live in a small flat.', { explanation: '*Piso* is masculine → *pequeño*.' }),
    listen('¿Hay un baño en el piso?', 'Is there a bathroom in the flat?'),
    order('Mi casa tiene un jardín grande', 'My house has a big garden'),
    translate('I live in a small flat', ['Vivo en un piso pequeño']),
    conversation('Emma’s new flat', [
      emma('¡Tengo un piso nuevo en Madrid!', 'I have a new flat in Madrid!'),
      emma(
        '¿Vives en una casa o en un piso?',
        'Do you live in a house or a flat?',
        you(['En una casa {any}', 'En un piso {any}', 'Vivo en {any}'], 'In a flat.', { hint: 'Vivo en un piso', wrong: ['Me gusta leer', 'Hoy es sábado'] }),
      ),
      emma(
        '¿Y cómo es? ¿Grande o pequeño?',
        'And what is it like? Big or small?',
        you(['Grande {any}', 'Pequeño {any}', 'Pequeña {any}', 'Es {any}', '{any} grande', '{any} pequeño', '{any} pequeña'], "It's small.", {
          hint: 'Es pequeño',
          wrong: ['Tengo dos hermanas', 'Quiero un zumo'],
        }),
      ),
      emma('El mío es pequeño también… pero tiene una cocina preciosa.', 'Mine is small too… but it has a gorgeous kitchen.'),
    ]),
  ],
});
