import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  understand,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l2-verbs',
  title: 'I Speak, You Speak',
  description: 'Your first -ar verbs: speak, work, study, listen',
  emoji: '🗣️',
  vocabulary: [
    word('hablar', 'hablar', 'to speak', 'verbs', { pron: 'a-BLAR', enAlt: ['to talk', 'speak'] }),
    word('hablo', 'hablo', 'I speak', 'verbs', { pron: 'A-blo', enAlt: ['i talk'] }),
    word('hablas', 'hablas', 'you speak', 'verbs', { pron: 'A-blas', enAlt: ['you talk'] }),
    word('habla', 'habla', 'he/she speaks', 'verbs', { pron: 'A-bla', enAlt: ['he speaks', 'she speaks', 'speaks'] }),
    word('trabajo', 'trabajo', 'I work', 'verbs', { pron: 'tra-BA-ho', note: '*El trabajo* also means "the job".' }),
    word('estudio', 'estudio', 'I study', 'verbs', { pron: 'es-TOO-dyo' }),
    word('escucho', 'escucho', 'I listen', 'verbs', { pron: 'es-KOO-cho', enAlt: ['i listen to'] }),
    word('cocino', 'cocino', 'I cook', 'verbs', { pron: 'ko-THEE-no' }),
    word('un-poco', 'un poco', 'a little', 'basics', { pron: 'oon PO-ko', enAlt: ['a bit'] }),
    word('musica', 'la música', 'music', 'leisure', { pron: 'la MOO-see-ka', enAlt: ['the music'] }),
  ],
  exercises: [
    intro('hablar', { lines: ['Verbs time! *Hablar* — to speak. Its ending, *-ar*, is the key.'] }),
    intro('hablo', { lines: ['Drop *-ar*, add *-o*: *hablo* — I speak. *Hablo inglés.*'] }),
    intro('hablas', { lines: ['Talking to a friend? *-as*: *¿hablas español?*'] }),
    intro('habla', { lines: ['About someone else: *-a*. *Emma habla español.*'] }),
    tip(
      'The -ar pattern',
      'Most verbs ending in *-ar* follow the same pattern. Learn *hablar* and you know hundreds: *hablo, hablas, habla*. And no need for "I" — *hablo* already means "I speak".',
      [
        { spanish: 'Hablo inglés.', english: 'I speak English.' },
        { spanish: '¿Hablas español?', english: 'Do you speak Spanish?' },
        { spanish: 'Mi madre habla francés.', english: 'My mother speaks French.' },
      ],
    ),
    question('*Yo* ___ español — which fits?', 'hablo', ['hablas', 'habla']),
    speak('Hablo un poco de español', 'I speak a little Spanish'),
    intro('un-poco'),
    intro('trabajo'),
    intro('estudio'),
    meaning('estudio'),
    intro('escucho'),
    intro('musica'),
    intro('cocino', { lines: ['*Cocino* — I cook. (I’m more of a *tortilla* specialist.)'] }),
    match('trabajo', 'estudio', 'escucho', 'cocino', 'hablo'),
    fill('¿___ inglés?', 'Hablas', ['Hablo', 'Hablar'], 'Do you speak English?', { explanation: 'Asking "you" → *hablas*.' }),
    recall('escucho'),
    listen('Trabajo en Madrid', 'I work in Madrid'),
    order('Escucho música en casa', 'I listen to music at home'),
    translate('I study Spanish', ['Estudio español', 'Yo estudio español']),
    understand('Mi hermana habla inglés y español', ['My sister speaks English and Spanish']),
    conversation('Languages and work', [
      emma(
        '¿Hablas español?',
        'Do you speak Spanish?',
        you(['Sí {any}', 'Hablo {any}', 'Un poco {any}', 'No {any}'], 'A little.', {
          hint: 'Hablo un poco de español',
          wrong: ['Me gusta el queso', 'Son las dos'],
        }),
      ),
      emma(
        '¡Muy bien! ¿Trabajas o estudias?',
        'Very good! Do you work or study?',
        you(['Trabajo {any}', 'Estudio {any}', 'Las dos cosas', 'Trabajo y estudio'], 'I work.', {
          hint: 'Trabajo',
          wrong: ['Tengo una hermana', 'Hoy es lunes'],
        }),
      ),
      emma('Yo trabajo aquí, ¡hablando contigo!', 'I work here — talking with you!'),
    ]),
  ],
});
