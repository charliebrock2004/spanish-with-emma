import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l2-days',
  title: 'Days of the Week',
  description: 'Lunes to domingo, today and tomorrow',
  emoji: '📅',
  vocabulary: [
    word('lunes', 'lunes', 'Monday', 'time', { pron: 'LOO-nes' }),
    word('martes', 'martes', 'Tuesday', 'time', { pron: 'MAR-tes' }),
    word('miercoles', 'miércoles', 'Wednesday', 'time', { pron: 'MYER-ko-les' }),
    word('jueves', 'jueves', 'Thursday', 'time', { pron: 'HWEH-bes' }),
    word('viernes', 'viernes', 'Friday', 'time', { pron: 'BYER-nes' }),
    word('sabado', 'sábado', 'Saturday', 'time', { pron: 'SA-ba-do' }),
    word('domingo', 'domingo', 'Sunday', 'time', { pron: 'do-MEEN-go' }),
    word('hoy', 'hoy', 'today', 'time', { pron: 'oy' }),
    word('manana', 'mañana', 'tomorrow', 'time', { pron: 'ma-NYA-na', note: '*Mañana* also means "morning".' }),
    word('fin-de-semana', 'el fin de semana', 'the weekend', 'time', { pron: 'el feen deh seh-MA-na', enAlt: ['weekend'] }),
    word('que-dia-es-hoy', '¿qué día es hoy?', 'what day is it today?', 'questions', { pron: 'keh DEE-a es OY', enAlt: ['what day is it?'] }),
  ],
  exercises: [
    intro('lunes', { lines: ['The week starts on *lunes* — Monday. Everyone’s favourite. 🙃'] }),
    intro('martes'),
    intro('miercoles'),
    meaning('martes'),
    intro('jueves', { lines: ['*Jueves* — Thursday. The *j* is that breathy Spanish "h".'] }),
    intro('viernes', { lines: ['*¡Viernes!* Friday. The best word in any language.'] }),
    match('lunes', 'martes', 'miercoles', 'jueves', 'viernes'),
    intro('sabado'),
    intro('domingo'),
    intro('fin-de-semana', { lines: ['*Sábado* and *domingo* make *el fin de semana* — the weekend.'] }),
    recall('domingo'),
    tip(
      'Days are lowercase',
      'In Spanish the days don’t take a capital letter: *lunes*, not *Lunes*. To say "on Monday", use *el*: *el lunes*. Every Monday: *los lunes*.',
      [
        { spanish: 'El sábado tengo fútbol.', english: 'On Saturday I have football.' },
        { spanish: 'Los domingos como con mi familia.', english: 'On Sundays I eat with my family.' },
      ],
    ),
    intro('hoy'),
    intro('manana'),
    intro('que-dia-es-hoy'),
    speak('Hoy es viernes', 'Today is Friday'),
    listen('Mañana es sábado', 'Tomorrow is Saturday'),
    question('If *hoy es lunes*, what is *mañana*?', 'martes', ['domingo', 'jueves']),
    fill('___ domingos como con mi familia.', 'Los', ['El', 'La'], 'On Sundays I eat with my family.', {
      explanation: 'Every Sunday → *los domingos*.',
    }),
    order('El fin de semana es mañana', 'The weekend is tomorrow'),
    translate('Today is Wednesday', ['Hoy es miércoles']),
    conversation('Which day is it?', [
      emma(
        '¿Qué día es hoy?',
        'What day is it today?',
        you(['Hoy es {any}', 'Es {any}', 'lunes', 'martes', 'miércoles', 'jueves', 'viernes', 'sábado', 'domingo'], 'Today is Friday.', {
          hint: 'Hoy es viernes',
          wrong: ['Tengo un hermano', 'Quiero un café'],
        }),
      ),
      emma(
        '¿Y cuál es tu día favorito?',
        'And what’s your favourite day?',
        you(['{any} lunes', '{any} martes', '{any} miércoles', '{any} jueves', '{any} viernes', '{any} sábado', '{any} domingo'], 'Saturday.', {
          hint: 'Mi día favorito es el sábado',
          wrong: ['Me gusta el pan', 'Buenas noches'],
        }),
      ),
      emma('¡El mío es el viernes! ¿Por qué? Porque mañana es sábado. 😄', 'Mine’s Friday! Why? Because tomorrow is Saturday.'),
    ]),
  ],
});
