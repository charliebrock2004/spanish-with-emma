import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l2-time',
  title: 'What Time Is It?',
  description: 'Tell the time and say when things happen',
  emoji: '⏰',
  vocabulary: [
    word('que-hora-es', '¿qué hora es?', 'what time is it?', 'questions', { pron: 'keh O-ra es' }),
    word('es-la-una', 'es la una', "it's one o'clock", 'time', { pron: 'es la OO-na', enAlt: ["it is one o'clock", "it's one"] }),
    word('son-las-dos', 'son las dos', "it's two o'clock", 'time', { pron: 'son las DOS', enAlt: ["it is two o'clock", "it's two"] }),
    word('y-media', 'y media', 'half past', 'time', { pron: 'ee MEH-dya', enAlt: ['and a half', 'thirty'] }),
    word('y-cuarto', 'y cuarto', 'quarter past', 'time', { pron: 'ee KWAR-to', enAlt: ['and a quarter', 'fifteen'] }),
    word('menos-cuarto', 'menos cuarto', 'quarter to', 'time', { pron: 'MEH-nos KWAR-to' }),
    word('a-las', 'a las', "at … o'clock", 'time', { pron: 'a las', enAlt: ['at'] }),
    word('de-la-manana', 'de la mañana', 'in the morning', 'time', { pron: 'deh la ma-NYA-na', enAlt: ['am', 'a.m.'] }),
    word('de-la-tarde', 'de la tarde', 'in the afternoon', 'time', { pron: 'deh la TAR-deh', enAlt: ['in the evening', 'pm', 'p.m.'] }),
    word('de-la-noche', 'de la noche', 'at night', 'time', { pron: 'deh la NO-cheh', enAlt: ['in the evening', 'pm', 'p.m.'] }),
  ],
  exercises: [
    intro('que-hora-es'),
    intro('es-la-una', { lines: ['One o’clock is singular: *es la una*.'] }),
    intro('son-las-dos', { lines: ['Every other hour is plural: *son las dos, son las tres, son las diez*.'] }),
    question('How do you say "it’s three o’clock"?', 'Son las tres', ['Es la tres', 'Es las tres']),
    speak('Son las cinco', "It's five o'clock"),
    intro('y-media', { lines: ['Half past: *y media*. *Son las dos y media* — half past two.'] }),
    intro('y-cuarto'),
    intro('menos-cuarto', { lines: ['Quarter to three is "three minus a quarter": *son las tres menos cuarto*.'] }),
    match('y-media', 'y-cuarto', 'menos-cuarto', 'es-la-una', 'son-las-dos'),
    listen('Son las cuatro y media', "It's half past four"),
    meaning('menos-cuarto'),
    tip(
      'Morning, afternoon, night',
      'Spain runs late! *De la tarde* covers the afternoon and early evening (lunch at 2, dinner at 9 or 10). After dark it’s *de la noche*.',
      [
        { spanish: 'Son las diez de la mañana.', english: "It's ten in the morning." },
        { spanish: 'Son las nueve de la noche.', english: "It's nine at night." },
      ],
    ),
    intro('de-la-manana'),
    intro('de-la-tarde'),
    intro('de-la-noche'),
    intro('a-las', { lines: ['To say *when* something happens: *a las*. *Como a las dos* — I eat at two.'] }),
    fill('Ceno ___ nueve.', 'a las', ['son las', 'es la'], 'I have dinner at nine.', { explanation: 'At a time → *a las*.' }),
    recall('de-la-tarde'),
    order('Son las siete de la tarde', "It's seven in the evening"),
    translate("It's half past one", ['Es la una y media']),
    conversation('Emma checks the time', [
      emma(
        'Perdona, ¿qué hora es?',
        'Excuse me, what time is it?',
        you(['Es la {any}', 'Son las {any}', 'Las {any}'], "It's three o'clock.", {
          hint: 'Son las tres',
          wrong: ['Hoy es lunes', 'Me gusta el café'],
        }),
      ),
      emma(
        '¡Uy, qué tarde! ¿A qué hora comes normalmente?',
        'Oops, it’s late! What time do you usually have lunch?',
        you(['A las {any}', 'Como a las {any}', 'A la una {any}'], 'At two.', {
          hint: 'A las dos',
          wrong: ['Tengo dos hermanos', 'Adiós'],
        }),
      ),
      emma('Yo como a las dos y media. ¡Muy español!', 'I have lunch at half past two. Very Spanish!'),
    ]),
  ],
});
