import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  recall,
  speak,
  tip,
  translate,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l2-family',
  title: 'My Family',
  description: 'Mum, dad, brothers, sisters and grandparents',
  emoji: '👨‍👩‍👧',
  vocabulary: [
    word('familia', 'la familia', 'family', 'family', { pron: 'la fa-MEE-lya', enAlt: ['the family'] }),
    word('mi', 'mi', 'my', 'basics', { pron: 'mee', note: 'Before a plural it becomes *mis*: *mis padres*.' }),
    word('madre', 'la madre', 'mother', 'family', { pron: 'la MA-dreh', enAlt: ['the mother', 'mum', 'mom'] }),
    word('padre', 'el padre', 'father', 'family', { pron: 'el PA-dreh', enAlt: ['the father', 'dad'] }),
    word('hermano', 'el hermano', 'brother', 'family', { pron: 'el er-MA-no', enAlt: ['the brother'], note: 'The *h* is silent.' }),
    word('hermana', 'la hermana', 'sister', 'family', { pron: 'la er-MA-na', enAlt: ['the sister'] }),
    word('padres', 'los padres', 'parents', 'family', { pron: 'los PA-dres', enAlt: ['the parents'] }),
    word('abuelo', 'el abuelo', 'grandfather', 'family', { pron: 'el a-BWEH-lo', enAlt: ['grandad', 'grandpa', 'the grandfather'] }),
    word('abuela', 'la abuela', 'grandmother', 'family', { pron: 'la a-BWEH-la', enAlt: ['gran', 'granny', 'grandma', 'the grandmother'] }),
    word('se-llama', 'se llama', 'is called', 'people', { pron: 'seh YA-ma', enAlt: ['his name is', 'her name is'] }),
  ],
  exercises: [
    intro('familia', { lines: ["*La familia.* Let's talk about the people you love — and the ones you're stuck with."] }),
    intro('mi', { lines: ['*Mi* means my: *mi familia* — my family.'] }),
    intro('madre'),
    intro('padre', { lines: ['And *mi padre* — my dad.'] }),
    meaning('madre'),
    intro('hermano'),
    intro('hermana', { lines: ['Change the *-o* to *-a* and a brother becomes a sister: *hermano, hermana*. Handy!'] }),
    recall('hermana'),
    tip(
      'Tengo — I have',
      'You know *tengo* from your age. It also means "I have": *tengo un hermano* — I have a brother. No brothers or sisters? *No tengo hermanos.*',
      [
        { spanish: 'Tengo una hermana.', english: 'I have a sister.' },
        { spanish: 'No tengo hermanos.', english: "I don't have any brothers or sisters." },
      ],
    ),
    speak('Tengo un hermano', 'I have a brother'),
    intro('padres', { lines: ['A funny one: *los padres* means parents — literally "the fathers".'] }),
    intro('abuelo'),
    intro('abuela'),
    match('madre', 'padre', 'hermano', 'hermana', 'abuela'),
    intro('se-llama', { lines: ['To give someone’s name: *mi abuela se llama Carmen* — my gran is called Carmen.'] }),
    listen('Mi abuela se llama Carmen', 'My grandmother is called Carmen'),
    fill('___ padres son de Escocia.', 'Mis', ['Mi', 'Tengo'], 'My parents are from Scotland.', {
      explanation: 'More than one → *mis*: *mis padres*, *mis hermanos*.',
    }),
    order('Tengo dos hermanas', 'I have two sisters'),
    translate('My father is called Juan', ['Mi padre se llama Juan']),
    speak('Mi madre se llama Ana', "My mother's called Ana", {
      prompt: "Tell me your mum's name — any name works.",
      accept: ['Mi madre se llama {any}'],
    }),
    conversation('Tell Emma about your family', [
      emma(
        '¿Tienes hermanos?',
        'Do you have any brothers or sisters?',
        you(['Tengo {any}', 'Sí tengo {any}', 'No tengo {any}', 'Sí', 'No'], 'I have a sister.', {
          hint: 'Tengo una hermana',
          wrong: ['Me llamo Emma', 'Buenos días'],
        }),
      ),
      emma('¡Qué bien! Yo tengo un hermano. Se llama David.', "Nice! I have a brother. He's called David."),
      emma(
        '¿Cómo se llama tu madre?',
        "What's your mother's name?",
        you(['Se llama {any}', 'Mi madre se llama {any}'], "She's called Ana.", {
          hint: 'Se llama Ana',
          wrong: ['Tengo dos hermanos', 'Estoy bien'],
        }),
      ),
      emma('¡Qué nombre tan bonito!', 'What a lovely name!'),
    ]),
  ],
});
