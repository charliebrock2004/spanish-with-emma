import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  question,
  recall,
  speak,
  tip,
  translate,
  word,
  you,
} from '@/lib/curriculum/dsl';

const COLOURS = ['rojo', 'azul', 'verde', 'amarillo', 'negro', 'blanco', 'rosa', 'naranja', 'gris', 'morado'];

export default defineLesson({
  id: 'l1-colours',
  title: 'Colours',
  description: 'Red, blue, green and friends',
  emoji: '🎨',
  difficulty: 2,
  vocabulary: [
    word('rojo', 'rojo', 'red', 'colours', { pron: 'RRO-ho', note: 'Roll the *r* at the start of a word.' }),
    word('azul', 'azul', 'blue', 'colours', { pron: 'a-THOOL' }),
    word('verde', 'verde', 'green', 'colours', { pron: 'BEHR-deh' }),
    word('amarillo', 'amarillo', 'yellow', 'colours', { pron: 'a-ma-REE-yo' }),
    word('negro', 'negro', 'black', 'colours', { pron: 'NEH-gro' }),
    word('blanco', 'blanco', 'white', 'colours', { pron: 'BLAN-ko' }),
    word('rosa', 'rosa', 'pink', 'colours', { pron: 'RRO-sa' }),
    word('naranja', 'naranja', 'orange', 'colours', { pron: 'na-RAN-ha', note: 'The *j* is a breathy "h" from the back of the throat.' }),
    word('gris', 'gris', 'grey', 'colours', { pron: 'GREES', enAlt: ['gray'] }),
    word('morado', 'morado', 'purple', 'colours', { pron: 'mo-RA-do' }),
    word('color', 'color', 'colour', 'colours', { pron: 'ko-LOR', enAlt: ['color'] }),
  ],
  exercises: [
    intro('rojo'),
    tip('Rolling your r', 'A single *r* at the start of a word, and every *rr*, is rolled — a quick trill of the tongue. Don\'t worry if it takes practice; everyone will understand you anyway.', [
      { spanish: 'rojo', english: 'red', pronunciation: 'RRO-ho' },
      { spanish: 'perro', english: 'dog', pronunciation: 'PEH-rro' },
    ]),
    intro('azul'),
    intro('verde'),
    meaning('verde'),
    intro('amarillo'),
    speak('amarillo'),
    intro('negro'),
    intro('blanco'),
    listen('blanco'),
    match('rojo', 'azul', 'verde', 'amarillo', 'negro', 'blanco'),
    intro('rosa'),
    intro('naranja'),
    intro('gris'),
    intro('morado'),
    recall('morado'),
    question('Mix *azul* and *amarillo* and you get…', 'verde', ['rojo', 'gris']),
    question('What colour is snow?', 'blanco', ['negro', 'naranja'], { lang: 'es' }),
    listen('naranja'),
    translate('red', ['rojo']),
    translate('purple', ['morado']),
    intro('color'),
    fill('El cielo es ___.', 'azul', ['negro', 'rosa'], 'The sky is blue.'),
    match('rosa', 'naranja', 'gris', 'morado', 'rojo'),
    speak('Mi color favorito es el azul', 'My favourite colour is blue'),
    conversation('Favourite colours', [
      emma(
        '¿Cuál es tu color favorito?',
        "What's your favourite colour?",
        you(COLOURS.map((c) => `{any} ${c}`), 'My favourite colour is green.', {
          hint: 'Mi color favorito es el verde',
          wrong: ['Me llamo Emma', 'Tengo frío'],
        }),
      ),
      emma('¡Qué bonito! El mío es el verde. 💚', "Lovely! Mine's green."),
    ]),
  ],
});
