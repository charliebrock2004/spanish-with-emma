import {
  conversation,
  defineLesson,
  emma,
  intro,
  listen,
  match,
  meaning,
  order,
  recall,
  speak,
  tip,
  translate,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l1-hola',
  title: '¡Hola!',
  description: 'Say hello and goodbye',
  emoji: '👋',
  difficulty: 1,
  minutes: 5,
  vocabulary: [
    word('hola', 'hola', 'hello', 'greetings', { pron: 'OH-la', enAlt: ['hi'], note: 'The h is silent.' }),
    word('adios', 'adiós', 'goodbye', 'greetings', { pron: 'a-DYOS', enAlt: ['bye'] }),
    word('buenos-dias', 'buenos días', 'good morning', 'greetings', { pron: 'BWEH-nos DEE-as' }),
    word('buenas-tardes', 'buenas tardes', 'good afternoon', 'greetings', {
      pron: 'BWEH-nas TAR-des',
      note: 'From lunchtime until it gets dark.',
    }),
    word('buenas-noches', 'buenas noches', 'good night', 'greetings', {
      pron: 'BWEH-nas NO-ches',
      enAlt: ['good evening'],
      note: 'Used in the evening as a greeting, and when going to bed.',
    }),
    word('hasta-luego', 'hasta luego', 'see you later', 'greetings', { pron: 'AS-ta LWEH-go', enAlt: ['bye'] }),
  ],
  exercises: [
    intro('hola', { lines: ['*¡Hola!*', 'That means hello.'] }),
    speak('hola', undefined, {
      prompt: 'Your turn — say *hola*.',
      success: "¡Perfecto! That's your first Spanish word.",
    }),
    meaning('hola'),
    tip('A silent h', 'The letter *h* is always silent in Spanish. *Hola* sounds like "OH-la" — never "HO-la".', [
      { spanish: 'hola', english: 'hello', pronunciation: 'OH-la' },
      { spanish: 'hasta luego', english: 'see you later', pronunciation: 'AS-ta LWEH-go' },
    ]),
    intro('adios', { lines: ['And when you leave: *adiós*.', 'That means goodbye.'] }),
    recall('adios'),
    listen('adios'),
    intro('buenos-dias', { lines: ['In the morning we say *buenos días*.'] }),
    speak('buenos-dias'),
    intro('buenas-tardes', { lines: ['After lunch it becomes *buenas tardes*.'] }),
    intro('buenas-noches', { lines: ['And in the evening, *buenas noches*.'] }),
    meaning('buenas-noches'),
    match('hola', 'adios', 'buenos-dias', 'buenas-noches'),
    intro('hasta-luego', { lines: ['A friendly way to say bye: *hasta luego*.'] }),
    listen('hasta-luego'),
    translate('Goodbye', ['Adiós', 'Hasta luego']),
    order('Hola, buenos días', 'Hello, good morning'),
    conversation('Your first chat', [
      emma('¡Hola!', 'Hello!', you('Hola', 'Hello!', { wrong: ['Adiós', 'Buenas noches'] })),
      emma('¡Buenos días!', 'Good morning!', you('Buenos días', 'Good morning!', { wrong: ['Buenas noches', 'Hasta luego'] })),
      emma('¡Hasta luego!', 'See you later!', you(['Adiós', 'Hasta luego'], 'Goodbye!', { wrong: ['Hola', 'Buenos días'] })),
      emma('¡Muy bien! 👏', 'Very good!'),
    ]),
  ],
});
