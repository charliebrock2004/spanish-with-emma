import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l1-como-estas',
  title: 'How Are You?',
  description: 'Ask how someone is — and answer',
  emoji: '😊',
  difficulty: 2,
  vocabulary: [
    word('como-estas', '¿cómo estás?', 'how are you?', 'questions', { pron: 'KO-mo es-TAS' }),
    word('estoy-bien', 'estoy bien', "I'm fine", 'feelings', {
      pron: 'es-TOY BYEN',
      enAlt: ["I'm well", "I'm good", 'I am fine'],
    }),
    word('muy-bien', 'muy bien', 'very well', 'feelings', { pron: 'mwee BYEN', enAlt: ['very good'] }),
    word('mal', 'mal', 'bad', 'feelings', { pron: 'MAL', enAlt: ['not well', 'badly'] }),
    word('mas-o-menos', 'más o menos', 'so-so', 'feelings', { pron: 'MAS o MEH-nos', enAlt: ['more or less'] }),
    word('genial', 'genial', 'great', 'feelings', {
      pron: 'heh-NYAL',
      note: 'A *g* before *e* or *i* sounds like a breathy "h".',
    }),
    word('cansado', 'cansado', 'tired', 'feelings', {
      pron: 'kan-SA-do',
      alt: ['cansada'],
      note: 'A woman says *cansada*.',
    }),
    word('que-tal', '¿qué tal?', "how's it going?", 'questions', { pron: 'keh TAL', enAlt: ["how's things?"] }),
  ],
  exercises: [
    intro('como-estas', { lines: ['*¿Cómo estás?* — how are you?'] }),
    intro('estoy-bien', { lines: ["The classic answer: *estoy bien* — I'm fine."] }),
    speak('estoy-bien'),
    intro('muy-bien', { lines: ['Feeling better than fine? *Muy bien*.'] }),
    meaning('muy-bien'),
    intro('mal'),
    intro('mas-o-menos', { lines: ['Not great, not terrible: *más o menos*.'] }),
    listen('mas-o-menos'),
    intro('genial'),
    tip(
      'Estoy — I am (right now)',
      'For how you feel, Spanish uses *estoy*: *estoy bien*, *estoy cansado*. There\'s another "I am" — *soy* — for who you are. We\'ll practise both.',
      [
        { spanish: 'Estoy cansado.', english: "I'm tired." },
        { spanish: 'Soy Emma.', english: "I'm Emma." },
      ],
    ),
    intro('cansado'),
    intro('que-tal', { lines: ['A more casual way to ask: *¿qué tal?*'] }),
    match('estoy-bien', 'mal', 'genial', 'cansado', 'mas-o-menos'),
    recall('genial'),
    order('Estoy muy bien, gracias', "I'm very well, thanks"),
    translate("I'm tired", ['Estoy cansado', 'Estoy cansada']),
    question('Which is a good answer to *¿Qué tal?*', 'Muy bien, gracias', ['Me llamo Emma', 'De nada']),
    fill('Estoy ___, gracias.', 'bien', ['buenos', 'hola'], "I'm fine, thanks."),
    listen('¿Y tú, cómo estás?', 'And you, how are you?'),
    conversation('How are you?', [
      emma(
        '¡Hola, {name}! ¿Cómo estás?',
        'Hi {name}! How are you?',
        you(['Estoy {any}', 'Muy bien {any}', 'Bien {any}', 'Genial', 'Más o menos', 'Mal'], "I'm fine.", {
          hint: 'Estoy bien, gracias',
          wrong: ['Me llamo Emma', 'Hasta luego'],
        }),
      ),
      emma('¡Qué bien! 😊', "That's great!", you(['¿Y tú?', 'Y tú', '¿Cómo estás?', '¿Qué tal?'], 'And you?', {
        hint: '¿Y tú?',
        wrong: ['Soy Emma', 'Por favor'],
      })),
      emma('Estoy genial, gracias.', "I'm great, thanks."),
    ]),
  ],
});
