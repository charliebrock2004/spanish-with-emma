import {
  conversation,
  defineLesson,
  emma,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l1-manners',
  title: 'Please & Thank You',
  description: 'Yes, no, please, thanks and sorry',
  emoji: '🙏',
  difficulty: 1,
  vocabulary: [
    word('si', 'sí', 'yes', 'basics', { pron: 'SEE', note: 'With the accent it means "yes"; *si* without it means "if".' }),
    word('no', 'no', 'no', 'basics', { pron: 'NO' }),
    word('gracias', 'gracias', 'thank you', 'basics', { pron: 'GRA-thyas', enAlt: ['thanks'] }),
    word('por-favor', 'por favor', 'please', 'basics', { pron: 'por fa-BOR' }),
    word('de-nada', 'de nada', "you're welcome", 'basics', { pron: 'de NA-da', enAlt: ['no problem'] }),
    word('muchas-gracias', 'muchas gracias', 'thank you very much', 'basics', {
      pron: 'MOO-chas GRA-thyas',
      enAlt: ['thanks a lot', 'many thanks'],
    }),
    word('perdon', 'perdón', 'excuse me', 'basics', { pron: 'per-DON', enAlt: ['sorry', 'pardon'] }),
    word('lo-siento', 'lo siento', "I'm sorry", 'basics', { pron: 'lo SYEN-to', enAlt: ['sorry'] }),
  ],
  exercises: [
    intro('si', { lines: ['*Sí* means *yes*…'] }),
    intro('no', { lines: ['…and *no* means *no*. Easy!'] }),
    meaning('si'),
    intro('gracias', { lines: ['*Gracias* — thank you.'] }),
    tip(
      'The Spanish "th"',
      'In Spain, *c* before *e* or *i* — and every *z* — sounds like the "th" in "think". So *gracias* is "GRA-thyas". In Latin America it\'s an "s" sound; both are correct.',
      [
        { spanish: 'gracias', english: 'thank you', pronunciation: 'GRA-thyas' },
        { spanish: 'cinco', english: 'five', pronunciation: 'THEEN-ko' },
      ],
    ),
    speak('gracias'),
    intro('por-favor', { lines: ['*Por favor* — please.'] }),
    recall('por-favor'),
    intro('de-nada', { lines: ["When someone thanks you, say *de nada* — you're welcome."] }),
    listen('de-nada'),
    match('si', 'no', 'gracias', 'por-favor', 'de-nada'),
    intro('muchas-gracias'),
    intro('perdon', { lines: ['*Perdón* gets you past someone, or says a quick sorry.'] }),
    intro('lo-siento', { lines: ['For a real apology: *lo siento*.'] }),
    question('You bump into someone on the metro. What do you say?', 'Perdón', ['De nada', 'Buenos días'], {
      explanation: '*Perdón* — "excuse me / sorry". Save *lo siento* for bigger apologies.',
    }),
    meaning('lo-siento'),
    translate('Thank you very much', ['Muchas gracias']),
    order('Sí, por favor', 'Yes, please'),
    order('No, gracias', 'No, thank you'),
    listen('Muchas gracias', 'Thank you very much'),
    speak('Sí, por favor', 'Yes, please'),
    conversation('At the café counter', [
      emma('¡Hola! ¿Un café?', 'Hi! A coffee?', you(['Sí, por favor', 'Sí'], 'Yes, please.', { wrong: ['De nada', 'Adiós'] })),
      emma('Aquí tienes.', 'Here you are.', you(['Gracias', 'Muchas gracias'], 'Thank you.', { wrong: ['Por favor', 'Perdón'] })),
      emma('De nada. ¡Hasta luego!', "You're welcome. See you later!", you(['Adiós', 'Hasta luego'], 'Goodbye!', { wrong: ['Sí', 'Lo siento'] })),
    ]),
  ],
});
