import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  understand,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l4-sightseeing',
  title: 'Seeing the Sights',
  description: 'Old towns, tickets, opening times and tours',
  emoji: '🏰',
  vocabulary: [
    word('casco-antiguo', 'el casco antiguo', 'the old town', 'travel', { enAlt: ['old town', 'historic centre'] }),
    word('catedral', 'la catedral', 'cathedral', 'travel', { enAlt: ['the cathedral'] }),
    word('entrada', 'la entrada', 'ticket (for entry)', 'travel', { enAlt: ['entrance ticket', 'ticket', 'entrance'] }),
    word('visita-guiada', 'la visita guiada', 'guided tour', 'travel', { enAlt: ['the guided tour', 'tour'] }),
    word('abierto', 'abierto', 'open', 'travel', { alt: ['abierta'] }),
    word('cerrado', 'cerrado', 'closed', 'travel', { alt: ['cerrada'], enAlt: ['shut'] }),
    word('merece-la-pena', 'merece la pena', "it's worth it", 'expressions', { enAlt: ["it's worthwhile", 'worth it'] }),
    word('hacer-fotos', 'hacer fotos', 'to take photos', 'travel', { enAlt: ['take photos', 'to take pictures'] }),
    word('horario', 'el horario', 'opening hours', 'travel', { enAlt: ['timetable', 'schedule', 'the opening hours'] }),
    word('gratis', 'gratis', 'free (no cost)', 'shopping', { enAlt: ['free', 'for free'] }),
  ],
  exercises: [
    intro('casco-antiguo', { lines: ['Every Spanish city has *un casco antiguo* — the old town. Get lost in it on purpose.'] }),
    intro('catedral'),
    intro('entrada'),
    intro('visita-guiada'),
    meaning('visita-guiada'),
    intro('horario'),
    intro('abierto'),
    intro('cerrado', { lines: ['Watch out: lots of places are *cerrado* at lunchtime. Siesta is real!'] }),
    match('catedral', 'entrada', 'abierto', 'cerrado', 'horario'),
    speak('¿A qué hora abre la catedral?', 'What time does the cathedral open?'),
    intro('gratis'),
    intro('hacer-fotos'),
    intro('merece-la-pena', { lines: ['Worth the queue? *¡Merece la pena!* — it’s worth it!'] }),
    recall('merece-la-pena'),
    tip(
      'Asking about visits',
      '*¿Cuánto cuesta la entrada?* (how much is a ticket?), *¿Se puede hacer fotos?* (can you take photos?), *¿Está abierto los lunes?* (is it open on Mondays?)',
      [{ spanish: 'Los domingos la entrada es gratis.', english: 'On Sundays entry is free.' }],
    ),
    question('A sign says *Cerrado los lunes*. That means…', 'Closed on Mondays', ['Open on Mondays', 'Free on Mondays']),
    fill('¿Se puede ___ fotos dentro?', 'hacer', ['tener', 'ir'], 'Can you take photos inside?'),
    listen('La visita guiada empieza a las once', 'The guided tour starts at eleven'),
    order('El casco antiguo merece la pena', 'The old town is worth it'),
    translate('Is the museum open today?', ['¿Está abierto el museo hoy?', '¿El museo está abierto hoy?', '¿Hoy está abierto el museo?']),
    understand('La entrada es gratis los domingos por la tarde', ['Entry is free on Sunday afternoons', 'The ticket is free on Sunday afternoons']),
    conversation('Tourist information', [
      emma(
        '¡Hola! Bienvenido a Toledo. ¿En qué le puedo ayudar?',
        'Hi! Welcome to Toledo. How can I help you?',
        you(['¿A qué hora {any}', '¿Cuánto cuesta {any}', '¿Hay {any}', '¿Dónde está {any}', 'Quiero {any}'], 'What time does the cathedral open?', {
          hint: '¿A qué hora abre la catedral?',
          wrong: ['Me gusta nadar', 'Tengo fiebre'],
        }),
      ),
      emma('Abre a las diez. También hay una visita guiada a las doce.', 'It opens at ten. There’s also a guided tour at twelve.'),
      emma(
        '¿Le interesa?',
        'Are you interested?',
        you(['Sí {any}', 'No {any}', '¿Cuánto cuesta {any}', 'Me encantaría {any}', 'Claro {any}'], 'Yes! How much is it?', {
          hint: 'Sí, ¿cuánto cuesta?',
          wrong: ['Fui ayer a la playa', 'Estoy de acuerdo'],
        }),
      ),
      emma('Diez euros. ¡Y merece la pena, se lo prometo!', "Ten euros. And it's worth it, I promise!"),
    ]),
  ],
});
