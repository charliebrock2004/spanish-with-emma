import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  understand,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l4-past-regular',
  title: 'Yesterday',
  description: 'The simple past: hablé, comí, viví',
  emoji: '⏪',
  vocabulary: [
    word('ayer', 'ayer', 'yesterday', 'time', { pron: 'a-YER' }),
    word('anoche', 'anoche', 'last night', 'time', { pron: 'a-NO-cheh' }),
    word('ano-pasado', 'el año pasado', 'last year', 'time', { enAlt: ['the year before'] }),
    word('semana-pasada', 'la semana pasada', 'last week', 'time'),
    word('hable', 'hablé', 'I spoke', 'verbs', { pron: 'a-BLEH', enAlt: ['i talked'] }),
    word('visite', 'visité', 'I visited', 'verbs', { pron: 'bee-see-TEH' }),
    word('comi', 'comí', 'I ate', 'verbs', { pron: 'ko-MEE', enAlt: ['i had lunch'] }),
    word('vivi', 'viví', 'I lived', 'verbs', { pron: 'bee-BEE' }),
    word('salio', 'salió', 'he/she went out', 'verbs', { enAlt: ['it left', 'he left', 'she left'] }),
    word('me-gusto', 'me gustó', 'I liked it', 'verbs', { pron: 'meh goos-TO', enAlt: ['i liked', 'i enjoyed it'] }),
  ],
  exercises: [
    tip(
      'Finished past',
      'For something finished at a specific time — *ayer*, *el año pasado* — Spanish uses the simple past (*pretérito*). The accent matters: *hablo* (I speak) vs *habló* (he spoke).',
      [
        { spanish: 'Ayer hablé con mi madre.', english: 'Yesterday I spoke to my mum.' },
        { spanish: 'El año pasado viví en Madrid.', english: 'Last year I lived in Madrid.' },
      ],
    ),
    intro('ayer'),
    intro('anoche'),
    intro('semana-pasada'),
    intro('ano-pasado'),
    match('ayer', 'anoche', 'semana-pasada', 'ano-pasado', 'hoy'),
    intro('hable', { lines: ['-ar verbs: *-é* for "I". *Hablé* — I spoke.'] }),
    intro('visite'),
    speak('Ayer visité el museo', 'Yesterday I visited the museum'),
    intro('comi', { lines: ['-er and -ir verbs: *-í*. *Comí, viví.*'] }),
    intro('vivi'),
    meaning('vivi'),
    intro('salio'),
    intro('me-gusto', { lines: ['Talking about something you enjoyed: *¡me gustó mucho!*'] }),
    recall('me-gusto'),
    question('*Hablo* or *hablé*? "Yesterday I spoke to Ana."', 'Ayer hablé con Ana', ['Ayer hablo con Ana', 'Ayer hablas con Ana']),
    fill('Anoche ___ en un restaurante italiano.', 'comí', ['como', 'comer'], 'Last night I ate at an Italian restaurant.'),
    listen('La semana pasada visité a mis abuelos', 'Last week I visited my grandparents'),
    order('El año pasado viví en Sevilla', 'Last year I lived in Seville'),
    translate('I liked it a lot', ['Me gustó mucho']),
    understand('Anoche salió con sus amigos', ['Last night he went out with his friends', 'Last night she went out with her friends']),
    conversation('What did you do?', [
      emma(
        '¿Qué hiciste ayer?',
        'What did you do yesterday?',
        you(['Ayer {any}', 'Visité {any}', 'Comí {any}', 'Hablé {any}', 'Trabajé {any}', 'Estudié {any}'], 'I visited a museum.', {
          hint: 'Visité un museo',
          wrong: ['Me duele el estómago', 'Hace viento'],
        }),
      ),
      emma(
        '¡Qué interesante! ¿Te gustó?',
        'How interesting! Did you like it?',
        you(['Sí {any}', 'Me gustó {any}', 'No {any}', 'Mucho {any}', 'Más o menos {any}'], 'Yes, I liked it a lot.', {
          hint: 'Sí, me gustó mucho',
          wrong: ['Cojo el tren', 'Tengo una maleta'],
        }),
      ),
      emma('Yo ayer comí con mi hermano y hablamos durante horas.', 'Yesterday I had lunch with my brother and we talked for hours.'),
    ]),
  ],
});
