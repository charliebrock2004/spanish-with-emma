import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  understand,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l4-opinions',
  title: 'What Do You Think?',
  description: 'Give opinions, agree and disagree',
  emoji: '💭',
  vocabulary: [
    word('creo-que', 'creo que', 'I think that', 'connectors', { enAlt: ['i believe that', 'i think'] }),
    word('me-parece-que', 'me parece que', 'it seems to me that', 'connectors', { enAlt: ['i think that', 'i reckon'] }),
    word('en-mi-opinion', 'en mi opinión', 'in my opinion', 'connectors'),
    word('estoy-de-acuerdo', 'estoy de acuerdo', 'I agree', 'expressions', { enAlt: ['i am in agreement'] }),
    word('no-estoy-de-acuerdo', 'no estoy de acuerdo', "I don't agree", 'expressions', { enAlt: ['i disagree', 'i do not agree'] }),
    word('tienes-razon', 'tienes razón', "you're right", 'expressions', { pron: 'TYEH-nes ra-THON', enAlt: ['you are right'] }),
    word('depende', 'depende', 'it depends', 'expressions'),
    word('que-opinas', '¿qué opinas?', 'what do you think?', 'questions', { enAlt: ["what's your opinion?"] }),
    word('interesante', 'interesante', 'interesting', 'adjectives'),
    word('aburrido', 'aburrido', 'boring', 'adjectives', { alt: ['aburrida'] }),
  ],
  exercises: [
    intro('que-opinas', { lines: ['Now let’s hear your opinions. *¿Qué opinas?*'] }),
    intro('creo-que'),
    intro('me-parece-que'),
    intro('en-mi-opinion'),
    speak('Creo que el español es precioso', 'I think Spanish is beautiful'),
    meaning('me-parece-que'),
    intro('interesante'),
    intro('aburrido'),
    tip(
      'Creo que + a sentence',
      'After *creo que* or *me parece que*, just say what you think as a normal sentence: *creo que es interesante*. (No "no creo que" yet — that needs a new tense, coming in Level 6!)',
      [
        { spanish: 'Me parece que es muy caro.', english: 'I think it’s very expensive.' },
        { spanish: 'En mi opinión, Madrid es más divertido.', english: 'In my opinion, Madrid is more fun.' },
      ],
    ),
    intro('estoy-de-acuerdo'),
    intro('no-estoy-de-acuerdo'),
    intro('tienes-razon'),
    intro('depende', { lines: ['And the diplomat’s favourite: *depende* — it depends. 😏'] }),
    match('estoy-de-acuerdo', 'tienes-razon', 'depende', 'interesante', 'aburrido'),
    recall('no-estoy-de-acuerdo'),
    question('Your friend says Glasgow is the best city in the world. You agree completely:', '¡Tienes razón!', ['Depende…', 'No estoy de acuerdo']),
    fill('Creo ___ la película es aburrida.', 'que', ['de', 'con'], 'I think the film is boring.'),
    listen('No estoy de acuerdo, me parece muy interesante', "I don't agree, I think it's very interesting"),
    order('En mi opinión, el fútbol es aburrido', 'In my opinion, football is boring'),
    translate('I think you’re right', ['Creo que tienes razón', 'Me parece que tienes razón']),
    understand('Depende del día', ['It depends on the day']),
    conversation('Friendly debate', [
      emma(
        'Creo que la tortilla está mejor con cebolla. ¿Qué opinas?',
        'I think tortilla is better with onion. What do you think?',
        you(['Estoy de acuerdo {any}', 'No estoy de acuerdo {any}', 'Tienes razón {any}', 'Creo que {any}', 'Depende {any}', 'Me parece que {any}', 'En mi opinión {any}'], 'I agree.', {
          hint: 'Estoy de acuerdo',
          wrong: ['Fui a la playa', 'El tren sale a las diez'],
        }),
      ),
      emma(
        'Otra pregunta: ¿el fútbol es interesante o aburrido?',
        'Another question: is football interesting or boring?',
        you(['{any} interesante {any}', '{any} aburrido {any}', 'Depende {any}', 'Creo que {any}', 'Me parece que {any}', 'En mi opinión {any}'], 'I think it’s interesting.', {
          hint: 'Creo que es interesante',
          wrong: ['Tengo dos maletas', 'Anoche comí paella'],
        }),
      ),
      emma('¡Buena respuesta! En España el fútbol es casi una religión.', 'Good answer! In Spain football is almost a religion.'),
    ]),
  ],
});
