import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  understand,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l4-stories',
  title: 'Telling a Story',
  description: 'First, then, suddenly, in the end…',
  emoji: '📖',
  vocabulary: [
    word('primero', 'primero', 'first', 'connectors', { enAlt: ['firstly', 'first of all'] }),
    word('luego', 'luego', 'then', 'connectors', { enAlt: ['later', 'next'] }),
    word('entonces', 'entonces', 'so / then', 'connectors', { enAlt: ['so', 'then'] }),
    word('de-repente', 'de repente', 'suddenly', 'connectors', { enAlt: ['all of a sudden'] }),
    word('al-final', 'al final', 'in the end', 'connectors', { enAlt: ['finally', 'at the end'] }),
    word('fue-increible', '¡fue increíble!', 'it was amazing!', 'expressions', { enAlt: ['it was incredible!'] }),
    word('fue-un-desastre', 'fue un desastre', 'it was a disaster', 'expressions'),
    word('conoci', 'conocí', 'I met', 'verbs', { enAlt: ['i got to know'] }),
    word('empezo', 'empezó', 'it started', 'verbs', { enAlt: ['it began', 'started'] }),
    word('por-suerte', 'por suerte', 'luckily', 'connectors', { enAlt: ['fortunately'] }),
  ],
  exercises: [
    intro('primero', { lines: ['Stories need glue. *Primero* — first.'] }),
    intro('luego'),
    intro('entonces'),
    intro('de-repente', { lines: ['My favourite: *de repente* — suddenly! Every good story has one.'] }),
    intro('al-final'),
    match('primero', 'luego', 'entonces', 'de-repente', 'al-final'),
    meaning('de-repente'),
    intro('por-suerte'),
    intro('empezo'),
    intro('conoci', { lines: ['*Conocí* — I met (for the first time). *Conocí a mi mejor amiga en Sevilla.*'] }),
    intro('fue-increible'),
    intro('fue-un-desastre'),
    recall('por-suerte'),
    tip(
      'A story in five words',
      'String past events together with *primero, luego, entonces, de repente, al final*. It instantly sounds natural.',
      [
        {
          spanish: 'Primero fuimos a la playa, luego comimos paella y al final bailamos toda la noche.',
          english: 'First we went to the beach, then we had paella and in the end we danced all night.',
        },
      ],
    ),
    question('Which word adds surprise to a story?', 'de repente', ['primero', 'luego']),
    fill('___ empezó a llover, pero por suerte teníamos paraguas.', 'De repente', ['Al final', 'Primero'], 'Suddenly it started to rain, but luckily we had umbrellas.'),
    listen('Al final perdimos el tren, pero fue increíble', 'In the end we missed the train, but it was amazing'),
    order('Primero visité la catedral y luego comí', 'First I visited the cathedral and then I had lunch'),
    translate('In the end it was a disaster', ['Al final fue un desastre']),
    speak('Conocí a gente muy simpática', 'I met some really nice people'),
    understand('Por suerte, un señor muy amable nos ayudó', ['Luckily, a very kind man helped us']),
    conversation('Tell Emma a travel story', [
      emma(
        'Cuéntame un viaje. ¿A dónde fuiste?',
        'Tell me about a trip. Where did you go?',
        you(['Fui a {any}', 'Estuve en {any}', 'Primero {any}', 'El año pasado {any}'], 'I went to Lisbon.', {
          hint: 'Fui a Lisboa',
          wrong: ['No funciona', 'Me gusta el pan'],
        }),
      ),
      emma(
        '¡Qué bien! ¿Y qué pasó?',
        'Nice! And what happened?',
        you(['Primero {any}', 'Luego {any}', 'De repente {any}', 'Conocí {any}', 'Visité {any}', 'Comí {any}', 'Fue {any}'], 'First I visited the old town.', {
          hint: 'Primero visité el casco antiguo',
          wrong: ['Tengo dos hermanos', 'Hace frío'],
        }),
      ),
      emma(
        '¿Y al final? ¿Qué tal fue?',
        'And in the end? How was it?',
        you(['Fue {any}', '¡Fue increíble!', 'Lo pasé {any}', 'Al final {any}', 'Fue un desastre {any}'], 'It was amazing!', {
          hint: '¡Fue increíble!',
          wrong: ['Me duele la espalda', 'Son las tres'],
        }),
      ),
      emma('¡Me encanta! Cuentas historias como una española.', 'I love it! You tell stories like a Spaniard.'),
    ]),
  ],
});
