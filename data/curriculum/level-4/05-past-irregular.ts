import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  understand,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l4-past-irregular',
  title: 'Where Did You Go?',
  description: 'Irregular past: fui, hice, tuve, estuve, vi',
  emoji: '🏖️',
  vocabulary: [
    word('fui', 'fui', 'I went', 'verbs', { note: '*Fui* is also "I was" (from *ser*). Context tells you which.' }),
    word('fue', 'fue', 'it was', 'verbs', { enAlt: ['he went', 'she went', 'was'] }),
    word('hice', 'hice', 'I did', 'verbs', { pron: 'EE-theh', enAlt: ['i made'] }),
    word('que-hiciste', '¿qué hiciste?', 'what did you do?', 'questions', { pron: 'keh ee-THEES-teh' }),
    word('tuve', 'tuve', 'I had', 'verbs'),
    word('estuve', 'estuve', 'I was', 'verbs', { enAlt: ['i stayed'] }),
    word('vi', 'vi', 'I saw', 'verbs', { pron: 'BEE' }),
    word('lo-pase-genial', 'lo pasé genial', 'I had a great time', 'expressions', { pron: 'lo pa-SEH heh-NYAL', enAlt: ['i had a brilliant time', 'i had a lovely time'] }),
    word('de-vacaciones', 'de vacaciones', 'on holiday', 'travel', { enAlt: ['on vacation'] }),
  ],
  exercises: [
    tip(
      'The irregular ones',
      'The most useful past verbs are irregular — and they have no accents. Learn them as words: *fui* (I went), *hice* (I did), *tuve* (I had), *estuve* (I was), *vi* (I saw).',
      [
        { spanish: 'El verano pasado fui a Mallorca.', english: 'Last summer I went to Mallorca.' },
        { spanish: 'Ayer tuve un día horrible.', english: 'Yesterday I had an awful day.' },
      ],
    ),
    intro('fui'),
    intro('de-vacaciones'),
    speak('Fui de vacaciones a Italia', 'I went on holiday to Italy'),
    intro('fue', { lines: ['*¿Qué tal fue?* — how was it? *¡Fue increíble!*'] }),
    intro('hice'),
    intro('que-hiciste'),
    meaning('que-hiciste'),
    intro('tuve'),
    intro('estuve', { lines: ['*Estuve* — I was (somewhere, for a while). *Estuve dos semanas en Cádiz.*'] }),
    intro('vi'),
    match('fui', 'hice', 'tuve', 'estuve', 'vi'),
    intro('lo-pase-genial', { lines: ['My favourite: *lo pasé genial* — I had a great time.'] }),
    recall('lo-pase-genial'),
    question('*¿Qué tal el concierto?* It was amazing. You say…', '¡Fue increíble!', ['¡Voy a ir!', '¡Es la una!']),
    fill('El sábado ___ a la playa con mis amigos.', 'fui', ['voy', 'fue'], 'On Saturday I went to the beach with my friends.'),
    fill('¿Qué ___ el fin de semana?', 'hiciste', ['hice', 'haces'], 'What did you do at the weekend?'),
    listen('Estuve una semana en Granada y lo pasé genial', 'I was in Granada for a week and had a great time'),
    order('Anoche vi una película muy buena', 'Last night I saw a really good film'),
    translate('I went to Spain last year', ['Fui a España el año pasado', 'El año pasado fui a España']),
    understand('Tuve un problema con el hotel', ['I had a problem with the hotel']),
    conversation('Holiday chat', [
      emma(
        '¿Qué hiciste el verano pasado?',
        'What did you do last summer?',
        you(['Fui {any}', 'Estuve {any}', 'Hice {any}', 'Visité {any}', 'Trabajé {any}'], 'I went to Portugal.', {
          hint: 'Fui a Portugal',
          wrong: ['Me gusta el café', 'Llueve mucho'],
        }),
      ),
      emma(
        '¡Qué envidia! ¿Qué tal fue?',
        "I'm jealous! How was it?",
        you(['Fue {any}', 'Lo pasé {any}', 'Muy bien {any}', 'Genial {any}', '¡Increíble! {any}'], 'I had a great time.', {
          hint: 'Lo pasé genial',
          wrong: ['Cojo el autobús', 'Tengo fiebre'],
        }),
      ),
      emma('Yo fui a Asturias. Llovió… ¡como en Escocia! Pero la comida fue espectacular.', 'I went to Asturias. It rained… like in Scotland! But the food was spectacular.'),
    ]),
  ],
});
