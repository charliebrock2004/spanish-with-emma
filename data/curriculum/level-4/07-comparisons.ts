import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  understand,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l4-comparisons',
  title: 'Better, Bigger, Best',
  description: 'Compare places and say what you prefer',
  emoji: '⚖️',
  vocabulary: [
    word('mas-que', 'más… que', 'more… than', 'grammar', { enAlt: ['more than', '-er than'] }),
    word('menos-que', 'menos… que', 'less… than', 'grammar', { enAlt: ['less than', 'fewer than'] }),
    word('tan-como', 'tan… como', 'as… as', 'grammar', { enAlt: ['as as'] }),
    word('mejor', 'mejor', 'better', 'adjectives', { enAlt: ['best'] }),
    word('peor', 'peor', 'worse', 'adjectives', { enAlt: ['worst'] }),
    word('prefiero', 'prefiero', 'I prefer', 'verbs'),
    word('el-mejor', 'el mejor', 'the best', 'adjectives', { alt: ['la mejor'] }),
    word('bonito', 'bonito', 'pretty', 'adjectives', { alt: ['bonita'], enAlt: ['beautiful', 'nice', 'lovely'] }),
    word('tranquilo', 'tranquilo', 'quiet', 'adjectives', { alt: ['tranquila'], enAlt: ['calm', 'peaceful'] }),
    word('ruidoso', 'ruidoso', 'noisy', 'adjectives', { alt: ['ruidosa'], enAlt: ['loud'] }),
  ],
  exercises: [
    intro('mas-que', { lines: ['*Más… que* — more… than. *Madrid es más grande que Toledo.*'] }),
    intro('menos-que'),
    intro('tan-como'),
    tip(
      'Comparing',
      '*más + adjective + que* (more … than), *menos + adjective + que* (less … than), *tan + adjective + como* (as … as). The adjective still matches: *Sevilla es más bonita que…*',
      [
        { spanish: 'El tren es más rápido que el autobús.', english: 'The train is faster than the bus.' },
        { spanish: 'Glasgow es tan bonito como Edimburgo.', english: 'Glasgow is as beautiful as Edinburgh.' },
      ],
    ),
    intro('bonito'),
    intro('tranquilo'),
    intro('ruidoso'),
    speak('Madrid es más ruidoso que Toledo', 'Madrid is noisier than Toledo'),
    meaning('tranquilo'),
    intro('mejor', { lines: ['Two irregulars: *mejor* (better) and *peor* (worse). Never "más bueno"!'] }),
    intro('peor'),
    intro('el-mejor'),
    intro('prefiero'),
    match('mejor', 'peor', 'prefiero', 'bonito', 'ruidoso'),
    recall('peor'),
    question('"Better than" is…', 'mejor que', ['más bueno que', 'más mejor que']),
    fill('El pueblo es más tranquilo ___ la ciudad.', 'que', ['como', 'de'], 'The village is quieter than the city.'),
    fill('Mi piso es tan grande ___ el tuyo.', 'como', ['que', 'de'], 'My flat is as big as yours.'),
    listen('Prefiero el tren porque es más cómodo', 'I prefer the train because it’s more comfortable'),
    order('La paella de mi abuela es la mejor', "My grandmother's paella is the best"),
    translate('The beach is better than the mountains', ['La playa es mejor que la montaña', 'La playa es mejor que las montañas']),
    understand('Este hotel es menos caro que el otro', ['This hotel is less expensive than the other one', 'This hotel is cheaper than the other one', 'This hotel is less expensive than the other']),
    conversation('This or that?', [
      emma(
        '¿Prefieres la playa o la montaña?',
        'Do you prefer the beach or the mountains?',
        you(['Prefiero {any}', '{any} playa {any}', '{any} montaña {any}', 'Depende {any}'], 'I prefer the beach.', {
          hint: 'Prefiero la playa',
          wrong: ['Fui ayer', 'Tengo un billete'],
        }),
      ),
      emma(
        '¿Por qué?',
        'Why?',
        you(['Porque {any}', 'Es más {any}', 'Es mejor {any}', 'Me gusta {any}', 'Me encanta {any}'], 'Because it’s more relaxing.', {
          hint: 'Porque es más tranquila',
          wrong: ['Son las dos', 'Me duele la cabeza'],
        }),
      ),
      emma('Buen argumento. Pero la montaña tiene menos gente… ¡y más tortilla!', 'Good point. But the mountains have fewer people… and more tortilla!'),
    ]),
  ],
});
