import {
  conversation,
  defineLesson,
  emma,
  fill,
  intro,
  listen,
  match,
  meaning,
  order,
  question,
  recall,
  speak,
  tip,
  translate,
  understand,
  word,
  you,
} from '@/lib/curriculum/dsl';

export default defineLesson({
  id: 'l4-perfect',
  title: 'Have You Ever…?',
  description: 'The perfect tense: he visitado, has comido',
  emoji: '🌍',
  vocabulary: [
    word('he', 'he', 'I have (done)', 'grammar', { enAlt: ['i have'] }),
    word('has', 'has', 'you have (done)', 'grammar', { enAlt: ['you have'] }),
    word('ha', 'ha', 'he/she has (done)', 'grammar', { enAlt: ['he has', 'she has', 'has'] }),
    word('hemos', 'hemos', 'we have (done)', 'grammar', { enAlt: ['we have'] }),
    word('he-estado', 'he estado', 'I have been', 'verbs', { enAlt: ["i've been"] }),
    word('he-comido', 'he comido', 'I have eaten', 'verbs', { enAlt: ["i've eaten", "i've had lunch"] }),
    word('he-visto', 'he visto', 'I have seen', 'verbs', { enAlt: ["i've seen"] }),
    word('alguna-vez', '¿alguna vez…?', 'ever…?', 'time', { enAlt: ['ever', 'have you ever'] }),
    word('nunca', 'nunca', 'never', 'time'),
    word('ya', 'ya', 'already', 'time', { enAlt: ['yet', 'now'] }),
    word('todavia-no', 'todavía no', 'not yet', 'time', { pron: 'to-da-BEE-a no', enAlt: ['still not'] }),
  ],
  exercises: [
    tip(
      'The perfect tense',
      'For things you’ve done (in your life, or today), use *he / has / ha / hemos* + a verb ending in *-ado* (for -ar verbs) or *-ido* (for -er/-ir verbs): *he visitado, he comido, he vivido*.',
      [
        { spanish: 'He visitado Sevilla.', english: "I've visited Seville." },
        { spanish: 'Hoy he comido paella.', english: "Today I've had paella." },
      ],
    ),
    intro('he'),
    intro('has'),
    intro('ha'),
    intro('hemos'),
    question('"I have visited" is…', 'he visitado', ['ha visitado', 'has visitado']),
    intro('he-estado', { lines: ['*He estado en…* — I’ve been to… Perfect for travel stories.'] }),
    speak('He estado en España', "I've been to Spain"),
    intro('he-comido'),
    intro('he-visto', { lines: ['Some are irregular: *ver* → *he visto*, *hacer* → *he hecho*.'] }),
    intro('alguna-vez'),
    intro('nunca'),
    meaning('nunca'),
    match('he-estado', 'he-comido', 'he-visto', 'nunca', 'ya'),
    intro('ya'),
    intro('todavia-no'),
    recall('todavia-no'),
    fill('¿___ estado alguna vez en México?', 'Has', ['He', 'Hemos'], 'Have you ever been to Mexico?'),
    fill('Nunca ___ visto el mar.', 'he', ['has', 'ha'], "I've never seen the sea."),
    listen('Hemos visitado Granada tres veces', "We've visited Granada three times"),
    order('¿Has comido paella alguna vez?', 'Have you ever eaten paella?'),
    translate("I've never been to Mexico", ['Nunca he estado en México', 'No he estado nunca en México']),
    understand('Ya he visto la catedral, pero todavía no he visto el museo', ["I've already seen the cathedral, but I haven't seen the museum yet"]),
    conversation('Travel stories', [
      emma(
        '¿Has estado alguna vez en España?',
        'Have you ever been to Spain?',
        you(['Sí {any}', 'No {any}', 'He estado {any}', 'Nunca {any}', 'Todavía no {any}'], "Yes, I've been to Barcelona.", {
          hint: 'Sí, he estado en Barcelona',
          wrong: ['Me gusta nadar', 'Cojo el metro'],
        }),
      ),
      emma(
        '¡Qué bien! ¿Has comido paella alguna vez?',
        'Great! Have you ever had paella?',
        you(['Sí {any}', 'No {any}', 'Nunca {any}', 'He comido {any}', 'Todavía no {any}'], "No, never — not yet!", {
          hint: 'No, todavía no',
          wrong: ['El tren sale a las diez', 'Llevo una camiseta'],
        }),
      ),
      emma('¡Pues tienes que probarla en Valencia! Yo invito. 😉', "Well, you’ll have to try it in Valencia! My treat."),
    ]),
  ],
});
